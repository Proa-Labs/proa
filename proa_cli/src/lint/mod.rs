fn lint_loop_case_conversions(
    path: &Path,
    file: &File,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    struct Visitor<'a> {
        path: &'a Path,
        suppressions: &'a SuppressionComments,
        ignored_ranges: &'a [RangeInclusive<usize>],
        diagnostics: &'a mut Vec<Diagnostic>,
        loop_depth: usize,
    }

    impl<'ast> Visit<'ast> for Visitor<'_> {
        fn visit_expr_for_loop(&mut self, node: &'ast syn::ExprForLoop) {
            self.loop_depth += 1;
            visit::visit_expr_for_loop(self, node);
            self.loop_depth -= 1;
        }

        fn visit_expr_loop(&mut self, node: &'ast syn::ExprLoop) {
            self.loop_depth += 1;
            visit::visit_expr_loop(self, node);
            self.loop_depth -= 1;
        }

        fn visit_expr_while(&mut self, node: &'ast syn::ExprWhile) {
            self.loop_depth += 1;
            visit::visit_expr_while(self, node);
            self.loop_depth -= 1;
        }

        fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
            if self.loop_depth > 0
                && matches!(
                    node.method.to_string().as_str(),
                    "contains" | "starts_with" | "ends_with"
                )
                && expr_contains_case_conversion(&node.receiver)
                && !line_in_ranges(node.span().start().line, self.ignored_ranges)
            {
                push_expr_diag_with_severity(
                    self.path,
                    SpanOrigin::File,
                    self.diagnostics,
                    self.suppressions,
                    node.span(),
                    Severity::Info,
                    "perf/lowercase-in-loop",
                    "case-converted string lookup inside a loop allocates for each item",
                    "precompute a normalized search/index field, normalize once before the loop, or compare with an allocation-free matcher",
                );
            }

            visit::visit_expr_method_call(self, node);
        }
    }

    let mut visitor = Visitor {
        path,
        suppressions,
        ignored_ranges,
        diagnostics,
        loop_depth: 0,
    };
    visitor.visit_file(file);
}

fn render_component_type_names(items: &[Item]) -> HashSet<String> {
    let mut names = HashSet::new();
    for item in items {
        let Item::Impl(item_impl) = item else {
            continue;
        };
        if let Some(name) = render_impl_self_name(item_impl) {
            names.insert(name);
        }
    }
    names
}

fn render_impl_self_name(item_impl: &ItemImpl) -> Option<String> {
    let Some((_, trait_path, _)) = &item_impl.trait_ else {
        return None;
    };
    if !is_render_trait(trait_path) {
        return None;
    }

    type_path_last_ident(&item_impl.self_ty)
}

fn check_render_component_struct(
    path: &Path,
    item_struct: &syn::ItemStruct,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    for field in &item_struct.fields {
        let field_name = field.ident.as_ref().map(|ident| ident.to_string());
        let span = field
            .ident
            .as_ref()
            .map_or_else(|| field.ty.span(), Spanned::span);

        if type_is_boxed_render_child(&field.ty) {
            push_expr_diag(
                path,
                SpanOrigin::File,
                diagnostics,
                suppressions,
                span,
                "render/boxed-child",
                "render component stores a boxed render child",
                "prefer generic child types so the render path stays monomorphized and allocation-free",
            );
        }

        if field_name.as_deref().is_some_and(field_name_is_render_text)
            && type_contains_owned_string(&field.ty)
        {
            push_expr_diag(
                path,
                SpanOrigin::File,
                diagnostics,
                suppressions,
                span,
                "render/string-child",
                "render component stores owned String text",
                "prefer `&str`, `Cow<'a, str>`, or generic children for render-only text",
            );
        }

        if field_name.as_deref().is_some_and(field_name_is_children) && type_contains_vec(&field.ty)
        {
            push_expr_diag(
                path,
                SpanOrigin::File,
                diagnostics,
                suppressions,
                span,
                "render/vec-children",
                "render component stores children in a Vec",
                "prefer static/generic child composition or borrowed slices for hot render paths",
            );
        }
    }
}

struct StructIndex {
    structs: HashMap<String, StructInfo>,
}

struct StructInfo {
    owned_fields: usize,
    is_render_component: bool,
}

impl StructIndex {
    fn new(items: &[Item], render_names: &HashSet<String>) -> Self {
        let mut structs = HashMap::new();
        for item in items {
            if let Item::Struct(item_struct) = item {
                let name = item_struct.ident.to_string();
                let owned_fields = item_struct
                    .fields
                    .iter()
                    .filter(|field| {
                        type_contains_owned_string(&field.ty) || type_contains_vec(&field.ty)
                    })
                    .count();
                structs.insert(
                    name.clone(),
                    StructInfo {
                        owned_fields,
                        is_render_component: render_names.contains(&name),
                    },
                );
            }
        }
        Self { structs }
    }

    fn is_owned_view_model(&self, name: &str) -> bool {
        let Some(info) = self.structs.get(name) else {
            return false;
        };
        !info.is_render_component
            && info.owned_fields >= 2
            && (name.ends_with("View")
                || name.ends_with("ViewModel")
                || name.ends_with("Row")
                || name.ends_with("Rows")
                || name.ends_with("Data"))
    }
}

fn check_render_api_perf(
    path: &Path,
    item_impl: &ItemImpl,
    method: &syn::ImplItemFn,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    let Some((_, trait_path, _)) = &item_impl.trait_ else {
        return;
    };
    if trait_path
        .segments
        .last()
        .is_none_or(|segment| segment.ident != "WebRender")
    {
        return;
    }

    // A child bound only by `WebRender` may await, so the impl cannot be
    // lowered to `WebRenderSync` regardless of what its own body does.
    let has_async_child_bound = generics_bind_async_render(&item_impl.generics, &["WebRender"])
        || generics_bind_async_render(&method.sig.generics, &["WebRender"]);

    if !has_async_child_bound
        && !block_completes_render_outcome_done(&method.block)
        && !block_forwards_foreign_render_outcome(&method.block)
        && !block_has_possibly_async_template_child(&method.block)
        && !block_contains_await(&method.block)
        && !block_contains_async_render_marker(&method.block)
    {
        push_expr_diag(
            path,
            SpanOrigin::File,
            diagnostics,
            suppressions,
            method.sig.ident.span(),
            "render/async-unneeded",
            "WebRender implementation does not await async work",
            "implement WebRenderSync unless the component truly needs async rendering",
        );
    }

    if !has_async_child_bound {
        check_async_html_static_subtree(path, &method.block, suppressions, diagnostics);
    }

    check_sync_child_in_async_template(path, &method.block, suppressions, diagnostics);
}

/// Flag `html!` invocations whose whole subtree is synchronous.
///
/// Async `html!` lowers to `async_html_from_fn(Box::new(|cx| Box::pin(async
/// move { .. })))`: one heap allocation for the erased closure, one for the
/// future, and dynamically dispatched polls. `html_sync!` lowers to a
/// monomorphized `OptimizedHtml<B, L, F>` with an `#[inline(always)]` render
/// and no allocation, so a static subtree inside an otherwise-async component
/// pays that cost for nothing.
fn check_async_html_static_subtree(
    path: &Path,
    block: &Block,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    struct Visitor<'a> {
        path: &'a Path,
        suppressions: &'a SuppressionComments,
        diagnostics: &'a mut Vec<Diagnostic>,
    }

    impl<'ast> Visit<'ast> for Visitor<'_> {
        fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
            if macro_path_ends(node, "html") {
                self.check_macro(node);
            }
            visit::visit_expr_macro(self, node);
        }
    }

    impl Visitor<'_> {
        fn check_macro(&mut self, node: &ExprMacro) {
            let tokens = &node.mac.tokens;
            if tokens_mention_ident(tokens, &["await"])
                || tokens_mention_ident(tokens, ASYNC_RENDER_MARKERS)
            {
                return;
            }
            let Ok(root) = syn::parse2::<HtmlRoot>(tokens.clone()) else {
                return;
            };
            if root.nodes.iter().any(html_node_has_async_child) {
                return;
            }
            push_expr_diag(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                node.mac.path.span(),
                "perf/async-html-static-subtree",
                "async html! template has no async children",
                "use html_sync! here; wrap the result with proa_core::to_async(...) if it is composed into an async tree",
            );
        }
    }

    let mut visitor = Visitor {
        path,
        suppressions,
        diagnostics,
    };
    visitor.visit_block(block);
}

/// Walk a template node, testing every interpolated slot with `matches`.
fn html_node_any_slot(node: &Node, matches: &impl Fn(&Expr) -> bool) -> bool {
    match node {
        Node::Element(el) => {
            el.attrs.iter().any(|attr| match attr {
                Attribute::Dynamic { value, .. } => matches(value),
                _ => false,
            }) || el
                .children
                .iter()
                .any(|child| html_node_any_slot(child, matches))
        }
        Node::Fragment(children) => children
            .iter()
            .any(|child| html_node_any_slot(child, matches)),
        Node::Block(expr) => matches(expr),
        Node::Text(_) | Node::Doctype(_) => false,
    }
}

/// Any component-like child that is not `to_async(..)`-wrapped keeps the
/// template async: until it is wrapped, its own trait impl decides.
fn html_node_has_async_child(node: &Node) -> bool {
    html_node_any_slot(node, &|expr| {
        !expr_is_async_render_wrapper(expr) && expr_references_uppercase_component(expr)
    })
}

/// Only a bare unit-struct child blocks the *impl-level* suggestion.
///
/// A call or struct-literal child is already presumed sync by
/// `render/sync-child-in-async`, which tells the author to wrap it in
/// `to_async(..)`. Treating it as async here would contradict that rule and
/// silence `render/async-unneeded` on exactly the components it targets.
fn html_node_has_opaque_child(node: &Node) -> bool {
    html_node_any_slot(node, &|expr| {
        !expr_is_async_render_wrapper(expr) && expr_is_bare_uppercase_path(expr)
    })
}

/// True when any `html!` in the block interpolates an opaque unit-struct child.
fn block_has_possibly_async_template_child(block: &Block) -> bool {
    struct Visitor {
        found: bool,
    }

    impl<'ast> Visit<'ast> for Visitor {
        fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
            if macro_path_ends(node, "html") {
                if let Ok(root) = syn::parse2::<HtmlRoot>(node.mac.tokens.clone()) {
                    if root.nodes.iter().any(html_node_has_opaque_child) {
                        self.found = true;
                    }
                }
            }
            visit::visit_expr_macro(self, node);
        }
    }

    let mut visitor = Visitor { found: false };
    visitor.visit_block(block);
    visitor.found
}

