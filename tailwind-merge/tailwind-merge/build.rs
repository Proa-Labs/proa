use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::PathBuf;

use serde::Deserialize;

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let config_path = manifest_dir.join("data").join("default_config.json");

    let data = fs::read_to_string(config_path).expect("read default config");
    let config: Config = serde_json::from_str(&data).expect("parse config");

    let mut group_ids = BTreeMap::new();
    let mut literal_entries: Vec<(String, String)> = Vec::new();
    let mut prefix_validator_entries: Vec<(String, ValidatorKind, String)> = Vec::new();
    let mut bare_validator_entries: Vec<(ValidatorKind, String)> = Vec::new();

    for (group, definitions) in &config.class_groups {
        if let Some(result) = expand_definitions(definitions, "", &config.theme) {
            let id = group_ids.len() as u16 + 1;
            group_ids.insert(group.clone(), id);

            for literal in result.literals {
                literal_entries.push((literal, group.clone()));
            }

            for (prefix, validator) in result.prefix_validators {
                prefix_validator_entries.push((prefix, validator, group.clone()));
            }

            for validator in result.bare_validators {
                bare_validator_entries.push((validator, group.clone()));
            }
        }
    }

    let mut conflicts = Vec::new();
    for (group, others) in &config.conflicting_class_groups {
        if let Some(id) = group_ids.get(group.as_str()) {
            let filtered: Vec<u16> = others
                .iter()
                .filter_map(|g| group_ids.get(g.as_str()).copied())
                .collect();
            let postfix: Vec<u16> = config
                .conflicting_class_group_modifiers
                .get(group)
                .map(|arr| {
                    arr.iter()
                        .filter_map(|g| group_ids.get(g.as_str()).copied())
                        .collect()
                })
                .unwrap_or_default();
            conflicts.push((*id, filtered, postfix));
        }
    }

    let max_conflicts = conflicts
        .iter()
        .map(|(_, list, postfix)| list.len().max(postfix.len()))
        .max()
        .unwrap_or(0)
        .max(1);

    literal_entries.sort();
    literal_entries.dedup();

    prefix_validator_entries.sort();
    prefix_validator_entries.dedup();

    bare_validator_entries.sort();
    bare_validator_entries.dedup();

    conflicts.sort_by_key(|(id, _, _)| *id);

    let mut output = String::new();
    output.push_str("// @generated by build.rs\n");
    output.push_str(&format!(
        "pub const MAX_CONFLICTS: usize = {};\n\n",
        max_conflicts
    ));

    let mut used_names = BTreeMap::new();
    let mut name_mapping = BTreeMap::new();
    output.push_str("pub mod groups {\n");
    for (name, id) in &group_ids {
        let mut const_name = sanitize_const_name(name);
        let mut counter = 1u32;
        while used_names.contains_key(&const_name) {
            const_name = format!("{}_{}", sanitize_const_name(name), counter);
            counter += 1;
        }
        used_names.insert(const_name.clone(), *id);
        name_mapping.insert(name.clone(), const_name.clone());
        output.push_str(&format!("    pub const {}: u16 = {};\n", const_name, id));
    }
    output.push_str("}\n\n");

    let mut order_sensitive = config.order_sensitive_modifiers.clone();
    order_sensitive.sort();
    order_sensitive.dedup();
    output.push_str("#[allow(dead_code)]\n");
    output.push_str("pub const ORDER_SENSITIVE_MODIFIERS: &[&str] = &[\n");
    for modifier in &order_sensitive {
        output.push_str(&format!("    \"{}\",\n", modifier));
    }
    output.push_str("];\n\n");

    output.push_str("pub const CLASS_ENTRIES: &[ClassEntry] = &[\n");
    for (class, group) in &literal_entries {
        let const_name = name_mapping
            .get(group)
            .cloned()
            .unwrap_or_else(|| sanitize_const_name(group));
        output.push_str(&format!(
            "    ClassEntry {{ class: \"{}\", group_id: groups::{} }},\n",
            class, const_name
        ));
    }
    output.push_str("];\n\n");

    output.push_str("pub const PREFIX_VALIDATORS: &[PrefixValidator] = &[\n");
    for (prefix, validator, group) in &prefix_validator_entries {
        let const_name = name_mapping
            .get(group)
            .cloned()
            .unwrap_or_else(|| sanitize_const_name(group));
        let requires_dash = if prefix.is_empty() { "false" } else { "true" };
        output.push_str(&format!(
            "    PrefixValidator {{ prefix: \"{}\", requires_dash: {}, validator: {}, group_id: groups::{} }},\n",
            prefix,
            requires_dash,
            validator.to_code(),
            const_name
        ));
    }
    output.push_str("];\n\n");

    output.push_str("pub const BARE_VALIDATORS: &[BareValidator] = &[\n");
    for (validator, group) in &bare_validator_entries {
        let const_name = name_mapping
            .get(group)
            .cloned()
            .unwrap_or_else(|| sanitize_const_name(group));
        output.push_str(&format!(
            "    BareValidator {{ validator: {}, group_id: groups::{} }},\n",
            validator.to_code(),
            const_name
        ));
    }
    output.push_str("];\n\n");

    output.push_str("pub const CONFLICT_SETS: &[ConflictSet] = &[\n");
    for (group_id, conflicts, postfix) in conflicts {
        output.push_str(&format!(
            "    ConflictSet {{ group_id: {}, conflicts: &{:?}, postfix_conflicts: &{:?} }},\n",
            group_id, conflicts, postfix
        ));
    }
    output.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("generated_data.rs"), output).expect("write generated data");
}

#[derive(Default)]
struct ExpandResult {
    literals: Vec<String>,
    prefix_validators: Vec<(String, ValidatorKind)>,
    bare_validators: Vec<ValidatorKind>,
}

impl ExpandResult {
    fn merge(&mut self, mut other: ExpandResult) {
        self.literals.append(&mut other.literals);
        self.prefix_validators.append(&mut other.prefix_validators);
        self.bare_validators.append(&mut other.bare_validators);
    }
}

fn expand_definitions(
    definitions: &[Definition],
    prefix: &str,
    theme: &BTreeMap<String, Vec<Definition>>,
) -> Option<ExpandResult> {
    let mut result = ExpandResult::default();

    for definition in definitions {
        match definition {
            Definition::Literal(value) => {
                let class = join_parts(prefix, value);
                result.literals.push(class);
            }
            Definition::Object(entries) => {
                for entry in entries {
                    let new_prefix = join_parts(prefix, &entry.key);
                    let child =
                        expand_definitions(entry.definitions.as_slice(), &new_prefix, theme)?;
                    result.merge(child);
                }
            }
            Definition::Theme(key) => {
                let theme_defs = theme.get(key)?;
                let child = expand_definitions(theme_defs.as_slice(), prefix, theme)?;
                result.merge(child);
            }
            Definition::Validator(name) => {
                let validator = ValidatorKind::from_name(name)?;
                if prefix.is_empty() {
                    result.bare_validators.push(validator);
                } else {
                    result
                        .prefix_validators
                        .push((prefix.to_string(), validator));
                }
            }
        }
    }

    result.literals.sort();
    result.literals.dedup();
    result.prefix_validators.sort();
    result.prefix_validators.dedup();
    result.bare_validators.sort();
    result.bare_validators.dedup();

    Some(result)
}

fn join_parts(prefix: &str, value: &str) -> String {
    if prefix.is_empty() {
        value.to_string()
    } else if value.is_empty() {
        prefix.to_string()
    } else {
        format!("{}-{}", prefix, value)
    }
}

fn sanitize_const_name(name: &str) -> String {
    let mut out = String::new();
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_uppercase());
        } else {
            out.push('_');
        }
    }
    if out
        .chars()
        .next()
        .map(|c| c.is_ascii_digit())
        .unwrap_or(false)
    {
        out.insert(0, '_');
    }
    out
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug)]
enum ValidatorKind {
    Any,
    AnyNonArbitrary,
    Number,
    Integer,
    Percent,
    Fraction,
    TshirtSize,
    ArbitraryValue,
    ArbitraryVariable,
    ArbitraryLength,
    ArbitraryNumber,
    ArbitrarySize,
    ArbitraryPosition,
    ArbitraryImage,
    ArbitraryShadow,
    ArbitraryVariableLength,
    ArbitraryVariableNumber,
    ArbitraryVariableSize,
    ArbitraryVariablePosition,
    ArbitraryVariableImage,
    ArbitraryVariableShadow,
    ArbitraryVariableFamilyName,
}

impl ValidatorKind {
    fn from_name(name: &str) -> Option<Self> {
        Some(match name {
            "is_any" => ValidatorKind::Any,
            "is_any_non_arbitrary" => ValidatorKind::AnyNonArbitrary,
            "is_number" => ValidatorKind::Number,
            "is_integer" => ValidatorKind::Integer,
            "is_percent" => ValidatorKind::Percent,
            "is_fraction" => ValidatorKind::Fraction,
            "is_tshirt_size" => ValidatorKind::TshirtSize,
            "is_arbitrary_value" => ValidatorKind::ArbitraryValue,
            "is_arbitrary_variable" => ValidatorKind::ArbitraryVariable,
            "is_arbitrary_length" => ValidatorKind::ArbitraryLength,
            "is_arbitrary_number" => ValidatorKind::ArbitraryNumber,
            "is_arbitrary_size" => ValidatorKind::ArbitrarySize,
            "is_arbitrary_position" => ValidatorKind::ArbitraryPosition,
            "is_arbitrary_image" => ValidatorKind::ArbitraryImage,
            "is_arbitrary_shadow" => ValidatorKind::ArbitraryShadow,
            "is_arbitrary_variable_length" => ValidatorKind::ArbitraryVariableLength,
            "is_arbitrary_variable_number" => ValidatorKind::ArbitraryVariableNumber,
            "is_arbitrary_variable_size" => ValidatorKind::ArbitraryVariableSize,
            "is_arbitrary_variable_position" => ValidatorKind::ArbitraryVariablePosition,
            "is_arbitrary_variable_image" => ValidatorKind::ArbitraryVariableImage,
            "is_arbitrary_variable_shadow" => ValidatorKind::ArbitraryVariableShadow,
            "is_arbitrary_variable_family_name" => ValidatorKind::ArbitraryVariableFamilyName,
            _ => return None,
        })
    }

    #[allow(clippy::wrong_self_convention)]
    fn to_code(&self) -> &'static str {
        match self {
            ValidatorKind::Any => "ValidatorKind::Any",
            ValidatorKind::AnyNonArbitrary => "ValidatorKind::AnyNonArbitrary",
            ValidatorKind::Number => "ValidatorKind::Number",
            ValidatorKind::Integer => "ValidatorKind::Integer",
            ValidatorKind::Percent => "ValidatorKind::Percent",
            ValidatorKind::Fraction => "ValidatorKind::Fraction",
            ValidatorKind::TshirtSize => "ValidatorKind::TshirtSize",
            ValidatorKind::ArbitraryValue => "ValidatorKind::ArbitraryValue",
            ValidatorKind::ArbitraryVariable => "ValidatorKind::ArbitraryVariable",
            ValidatorKind::ArbitraryLength => "ValidatorKind::ArbitraryLength",
            ValidatorKind::ArbitraryNumber => "ValidatorKind::ArbitraryNumber",
            ValidatorKind::ArbitrarySize => "ValidatorKind::ArbitrarySize",
            ValidatorKind::ArbitraryPosition => "ValidatorKind::ArbitraryPosition",
            ValidatorKind::ArbitraryImage => "ValidatorKind::ArbitraryImage",
            ValidatorKind::ArbitraryShadow => "ValidatorKind::ArbitraryShadow",
            ValidatorKind::ArbitraryVariableLength => "ValidatorKind::ArbitraryVariableLength",
            ValidatorKind::ArbitraryVariableNumber => "ValidatorKind::ArbitraryVariableNumber",
            ValidatorKind::ArbitraryVariableSize => "ValidatorKind::ArbitraryVariableSize",
            ValidatorKind::ArbitraryVariablePosition => "ValidatorKind::ArbitraryVariablePosition",
            ValidatorKind::ArbitraryVariableImage => "ValidatorKind::ArbitraryVariableImage",
            ValidatorKind::ArbitraryVariableShadow => "ValidatorKind::ArbitraryVariableShadow",
            ValidatorKind::ArbitraryVariableFamilyName => {
                "ValidatorKind::ArbitraryVariableFamilyName"
            }
        }
    }
}

#[derive(Deserialize)]
struct Config {
    #[serde(rename = "theme")]
    theme: BTreeMap<String, Vec<Definition>>,
    #[serde(rename = "classGroups")]
    class_groups: BTreeMap<String, Vec<Definition>>,
    #[serde(rename = "conflictingClassGroups", default)]
    conflicting_class_groups: BTreeMap<String, Vec<String>>,
    #[serde(rename = "conflictingClassGroupModifiers", default)]
    conflicting_class_group_modifiers: BTreeMap<String, Vec<String>>,
    #[serde(rename = "orderSensitiveModifiers", default)]
    order_sensitive_modifiers: Vec<String>,
}

#[derive(Deserialize)]
#[serde(tag = "type", content = "value")]
enum Definition {
    #[serde(rename = "literal")]
    Literal(String),
    #[serde(rename = "validator")]
    Validator(String),
    #[serde(rename = "theme")]
    Theme(String),
    #[serde(rename = "object")]
    Object(Vec<ObjectEntry>),
}

#[derive(Deserialize)]
struct ObjectEntry {
    key: String,
    definitions: Vec<Definition>,
}
