#[derive(Default)]
struct RsjsNamedClientLocalCollector {
    locals: HashMap<String, RsjsNamedClientLocalInfo>,
}

impl<'ast> Visit<'ast> for RsjsNamedClientLocalCollector {
    fn visit_local(&mut self, node: &'ast Local) {
        let Some(name) = local_plain_ident(&node.pat) else {
            visit::visit_local(self, node);
            return;
        };
        let Some(init) = &node.init else {
            visit::visit_local(self, node);
            return;
        };
        let Some(kind) = rsjs_named_client_local_kind(&init.expr) else {
            visit::visit_local(self, node);
            return;
        };
        self.locals.insert(
            name.clone(),
            RsjsNamedClientLocalInfo {
                name,
                kind,
                span: init.expr.span(),
            },
        );
        visit::visit_local(self, node);
    }
}

struct RsjsNamedClientLocalUsageCollector<'a> {
    local_names: &'a HashSet<String>,
    roots: HashSet<String>,
    edges: HashMap<String, HashSet<String>>,
    derived_edges: HashMap<String, HashSet<String>>,
    context: RsjsNamedClientLocalUseContext,
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum RsjsNamedClientLocalUseContext {
    ServerPrelude,
    ClientRoot,
    ClientDeclaration(String),
}

impl RsjsNamedClientLocalUsageCollector<'_> {
    fn record_use(&mut self, name: &str) {
        let deps = self.local_deps(name);
        if deps.is_empty() {
            return;
        }
        match &self.context {
            RsjsNamedClientLocalUseContext::ServerPrelude => {}
            RsjsNamedClientLocalUseContext::ClientRoot => {
                self.roots.extend(deps);
            }
            RsjsNamedClientLocalUseContext::ClientDeclaration(current) => {
                let edges = self.edges.entry(current.clone()).or_default();
                for dep in deps {
                    if current != &dep {
                        edges.insert(dep);
                    }
                }
            }
        }
    }

    fn local_deps(&self, name: &str) -> HashSet<String> {
        if self.local_names.contains(name) {
            return HashSet::from([name.to_string()]);
        }
        self.derived_edges.get(name).cloned().unwrap_or_default()
    }

    fn expr_client_deps(&self, expr: &Expr) -> HashSet<String> {
        let mut finder = RsjsNamedClientLocalDepFinder {
            local_names: self.local_names,
            derived_edges: &self.derived_edges,
            deps: HashSet::new(),
        };
        finder.visit_expr(expr);
        finder.deps
    }

    fn with_context(
        &mut self,
        context: RsjsNamedClientLocalUseContext,
        visit: impl FnOnce(&mut Self),
    ) {
        let previous = std::mem::replace(&mut self.context, context);
        visit(self);
        self.context = previous;
    }

    fn visit_template_node(&mut self, node: &Node) {
        match node {
            Node::Element(el) => {
                for attr in &el.attrs {
                    if let Attribute::Dynamic { value, .. } = attr {
                        self.with_context(RsjsNamedClientLocalUseContext::ClientRoot, |this| {
                            this.visit_expr(value);
                        });
                    }
                }
                for child in &el.children {
                    self.visit_template_node(child);
                }
            }
            Node::Fragment(children) => {
                for child in children {
                    self.visit_template_node(child);
                }
            }
            Node::Block(expr) => {
                self.with_context(RsjsNamedClientLocalUseContext::ClientRoot, |this| {
                    this.visit_expr(expr);
                });
            }
            Node::Text(_) | Node::Doctype(_) => {}
        }
    }
}

fn parse_rsjs_template_macro(mac: &syn::Macro) -> Option<HtmlRoot> {
    let dialect = match mac.path.segments.last()?.ident.to_string().as_str() {
        "html" | "html_sync" => MacroDialect::Html,
        "xml" | "xml_sync" => MacroDialect::Xml,
        _ => return None,
    };
    parse_markup_tokens(dialect, mac.tokens.clone()).ok()
}

impl<'ast> Visit<'ast> for RsjsNamedClientLocalUsageCollector<'_> {
    fn visit_local(&mut self, node: &'ast Local) {
        let Some(name) = local_plain_ident(&node.pat) else {
            visit::visit_local(self, node);
            return;
        };
        let Some(init) = &node.init else {
            visit::visit_local(self, node);
            return;
        };
        match rsjs_named_client_local_kind(&init.expr) {
            Some(RsjsNamedClientLocalKind::Signal | RsjsNamedClientLocalKind::SharedState) => {}
            Some(
                RsjsNamedClientLocalKind::Memo
                | RsjsNamedClientLocalKind::Handler
                | RsjsNamedClientLocalKind::EventHandler
                | RsjsNamedClientLocalKind::Query
                | RsjsNamedClientLocalKind::Mutation,
            ) => {
                self.with_context(
                    RsjsNamedClientLocalUseContext::ClientDeclaration(name),
                    |this| {
                        this.visit_expr(&init.expr);
                    },
                );
            }
            Some(RsjsNamedClientLocalKind::NodeRef) => {}
            None => {
                let deps = self.expr_client_deps(&init.expr);
                if !deps.is_empty() {
                    self.derived_edges.insert(name, deps);
                    return;
                }
                visit::visit_local(self, node);
            }
        }
    }

    fn visit_expr_path(&mut self, node: &'ast ExprPath) {
        if let Some(ident) = node.path.get_ident() {
            self.record_use(&ident.to_string());
            return;
        }
        visit::visit_expr_path(self, node);
    }

    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if let Expr::Path(path) = node.func.as_ref() {
            if let Some(ident) = path.path.get_ident() {
                self.record_use(&ident.to_string());
                for arg in &node.args {
                    self.visit_expr(arg);
                }
                return;
            }
        }
        visit::visit_expr_call(self, node);
    }

    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        if let Some(Ok(text)) = proa_dsl::text::parse_expr(&Expr::Macro(node.clone())) {
            for argument in &text.args {
                self.visit_expr(argument);
            }
            return;
        }

        if let Some(root) = parse_rsjs_template_macro(&node.mac) {
            for node in &root.nodes {
                self.visit_template_node(node);
            }
        }
        visit::visit_expr_macro(self, node);
    }

    fn visit_stmt_macro(&mut self, node: &'ast syn::StmtMacro) {
        if let Some(root) = parse_rsjs_template_macro(&node.mac) {
            for node in &root.nodes {
                self.visit_template_node(node);
            }
        }
        visit::visit_stmt_macro(self, node);
    }
}

struct RsjsNamedClientLocalDepFinder<'a> {
    local_names: &'a HashSet<String>,
    derived_edges: &'a HashMap<String, HashSet<String>>,
    deps: HashSet<String>,
}

impl RsjsNamedClientLocalDepFinder<'_> {
    fn record_use(&mut self, name: &str) {
        if self.local_names.contains(name) {
            self.deps.insert(name.to_string());
            return;
        }
        if let Some(deps) = self.derived_edges.get(name) {
            self.deps.extend(deps.iter().cloned());
        }
    }
}

impl<'ast> Visit<'ast> for RsjsNamedClientLocalDepFinder<'_> {
    fn visit_expr_path(&mut self, node: &'ast ExprPath) {
        if let Some(ident) = node.path.get_ident() {
            self.record_use(&ident.to_string());
            return;
        }
        visit::visit_expr_path(self, node);
    }

    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if let Expr::Path(path) = node.func.as_ref() {
            if let Some(ident) = path.path.get_ident() {
                self.record_use(&ident.to_string());
                for arg in &node.args {
                    self.visit_expr(arg);
                }
                return;
            }
        }
        visit::visit_expr_call(self, node);
    }
    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        if let Some(Ok(text)) = proa_dsl::text::parse_expr(&Expr::Macro(node.clone())) {
            for argument in &text.args {
                self.visit_expr(argument);
            }
        }
    }
}

/// Peel `(expr)` and invisible token groups so a shape check sees the real
/// expression.
fn strip_expr_wrappers(expr: &Expr) -> &Expr {
    match expr {
        Expr::Paren(paren) => strip_expr_wrappers(&paren.expr),
        Expr::Group(group) => strip_expr_wrappers(&group.expr),
        other => other,
    }
}

fn local_plain_ident(pat: &Pat) -> Option<String> {
    match pat {
        Pat::Ident(pat_ident) => Some(pat_ident.ident.to_string()),
        Pat::Type(pat_type) => local_plain_ident(&pat_type.pat),
        _ => None,
    }
}

fn rsjs_named_client_local_kind(expr: &Expr) -> Option<RsjsNamedClientLocalKind> {
    if expr_is_signal_call(expr) {
        return Some(RsjsNamedClientLocalKind::Signal);
    }
    match expr {
        Expr::Call(call) if call_path_is_rsjs_shared_state(call) => {
            Some(RsjsNamedClientLocalKind::SharedState)
        }
        Expr::Call(call) if call_path_ends(call, &["memo"]) => Some(RsjsNamedClientLocalKind::Memo),
        Expr::Call(call) if call_path_ends(call, &["handler"]) => {
            Some(RsjsNamedClientLocalKind::Handler)
        }
        Expr::Call(call) if call_path_ends(call, &["event_handler"]) => {
            Some(RsjsNamedClientLocalKind::EventHandler)
        }
        Expr::Call(call) if call_path_ends(call, &["node_ref"]) => {
            Some(RsjsNamedClientLocalKind::NodeRef)
        }
        Expr::Call(call)
            if call_path_ends(call, &["query"])
                || call_path_ends(call, &["query_with_options"])
                || call_path_ends(call, &["query_with_initial"]) =>
        {
            Some(RsjsNamedClientLocalKind::Query)
        }
        Expr::Call(call)
            if call_path_ends(call, &["mutation"])
                || call_path_ends(call, &["mutation_with_options"]) =>
        {
            Some(RsjsNamedClientLocalKind::Mutation)
        }
        Expr::Paren(paren) => rsjs_named_client_local_kind(&paren.expr),
        Expr::Group(group) => rsjs_named_client_local_kind(&group.expr),
        _ => None,
    }
}

fn lint_attr_value_impls(
    path: &Path,
    file: &File,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    lint_attr_value_impl_items(path, &file.items, suppressions, ignored_ranges, diagnostics);
}

fn lint_attr_value_impl_items(
    path: &Path,
    items: &[Item],
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    let wrappers = AttrWrapperIndex::new(items);
    for item in items {
        match item {
            Item::Impl(item_impl) => lint_attr_value_impl(
                path,
                item_impl,
                &wrappers,
                suppressions,
                ignored_ranges,
                diagnostics,
            ),
            Item::Mod(item_mod) => {
                if let Some((_, items)) = &item_mod.content {
                    lint_attr_value_impl_items(
                        path,
                        items,
                        suppressions,
                        ignored_ranges,
                        diagnostics,
                    );
                }
            }
            _ => {}
        }
    }
}

fn lint_attr_value_impl(
    path: &Path,
    item_impl: &ItemImpl,
    wrappers: &AttrWrapperIndex,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    let Some((_, trait_path, _)) = &item_impl.trait_ else {
        return;
    };
    if !is_attr_value_trait(trait_path) {
        return;
    }

    let impl_line = item_impl.impl_token.span.start().line;
    if !line_in_ranges(impl_line, ignored_ranges) {
        check_boolean_attr_value_wrapper_perf(path, item_impl, wrappers, suppressions, diagnostics);
    }

    for item in &item_impl.items {
        let ImplItem::Fn(method) = item else {
            continue;
        };
        if method.sig.ident != "render_attr_value" {
            continue;
        }
        let line = method.sig.ident.span().start().line;
        if line_in_ranges(line, ignored_ranges) {
            continue;
        }
        check_attr_value_block_perf(
            path,
            attr_value_impl_self_name(item_impl).as_deref(),
            wrappers,
            method.sig.ident.span(),
            &method.block,
            suppressions,
            diagnostics,
        );
    }
}

fn check_boolean_attr_value_wrapper_perf(
    path: &Path,
    item_impl: &ItemImpl,
    wrappers: &AttrWrapperIndex,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    let Some(name) = attr_value_impl_self_name(item_impl) else {
        return;
    };
    if !wrappers.is_private_struct(&name) || !attr_value_impl_is_boolean_wrapper(item_impl) {
        return;
    }

    push_expr_diag_with_severity(
        path,
        SpanOrigin::File,
        diagnostics,
        suppressions,
        item_impl.impl_token.span,
        Severity::Info,
        "render/bool-attr-wrapper",
        "private AttrValue wrapper only mirrors a boolean attribute",
        "remove the wrapper and pass the condition directly, e.g. `selected={condition}`",
    );
}

fn check_attr_value_block_perf(
    path: &Path,
    self_name: Option<&str>,
    wrappers: &AttrWrapperIndex,
    summary_span: proc_macro2::Span,
    block: &Block,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    let mut visitor = AttrValueVisitor {
        path,
        suppressions,
        diagnostics,
        stream_ops: 0,
        has_control_flow: false,
        has_text_macro: false,
    };
    visitor.visit_block(block);

    if visitor.stream_ops >= 2 && !visitor.has_control_flow && !visitor.has_text_macro {
        push_expr_diag_with_severity(
            visitor.path,
            SpanOrigin::File,
            visitor.diagnostics,
            visitor.suppressions,
            summary_span,
            Severity::Info,
            "render/manual-attr-stream",
            "manual AttrValue streaming can usually be expressed as one composable template",
            "prefer `text!(...)` or a nested AttrValue component so escaping and byte layout stay centralized",
        );
    }

    if self_name.is_some_and(|name| wrappers.is_one_off_attr_wrapper(name))
        && visitor.stream_ops >= 2
        && !visitor.has_control_flow
        && !visitor.has_text_macro
    {
        push_expr_diag_with_severity(
            visitor.path,
            SpanOrigin::File,
            visitor.diagnostics,
            visitor.suppressions,
            summary_span,
            Severity::Info,
            "render/one-off-attr-wrapper",
            "private one-off AttrValue wrapper only concatenates attribute pieces",
            "inline text!(...) at the call site or in render_attr_value so the wrapper can disappear",
        );
    }
}

struct AttrWrapperIndex {
    private_structs: HashSet<String>,
    constructor_counts: HashMap<String, usize>,
}

impl AttrWrapperIndex {
    fn new(items: &[Item]) -> Self {
        let private_structs = items
            .iter()
            .filter_map(|item| {
                let Item::Struct(item_struct) = item else {
                    return None;
                };
                if !matches!(item_struct.vis, syn::Visibility::Inherited) {
                    return None;
                }
                Some(item_struct.ident.to_string())
            })
            .collect();

        let mut counter = ConstructorUseCounter {
            counts: HashMap::new(),
        };
        for item in items {
            counter.visit_item(item);
        }

        Self {
            private_structs,
            constructor_counts: counter.counts,
        }
    }

    fn is_one_off_attr_wrapper(&self, name: &str) -> bool {
        self.private_structs.contains(name)
            && self.constructor_counts.get(name).copied().unwrap_or(0) == 1
    }

    fn is_private_struct(&self, name: &str) -> bool {
        self.private_structs.contains(name)
    }
}

struct ConstructorUseCounter {
    counts: HashMap<String, usize>,
}

impl ConstructorUseCounter {
    fn bump_path(&mut self, path: &SynPath) {
        if let Some(name) = path_last_ident(path) {
            *self.counts.entry(name).or_insert(0) += 1;
        }
    }

    fn visit_template_node(&mut self, node: &Node) {
        match node {
            Node::Element(el) => {
                for attr in &el.attrs {
                    if let Attribute::Dynamic { value, .. } = attr {
                        self.visit_expr(value);
                    }
                }
                for child in &el.children {
                    self.visit_template_node(child);
                }
            }
            Node::Fragment(children) => {
                for child in children {
                    self.visit_template_node(child);
                }
            }
            Node::Block(expr) => self.visit_expr(expr),
            Node::Text(_) | Node::Doctype(_) => {}
        }
    }
}

impl<'ast> Visit<'ast> for ConstructorUseCounter {
    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if let Expr::Path(path) = node.func.as_ref() {
            self.bump_path(&path.path);
        }
        visit::visit_expr_call(self, node);
    }

    fn visit_expr_struct(&mut self, node: &'ast syn::ExprStruct) {
        self.bump_path(&node.path);
        visit::visit_expr_struct(self, node);
    }

    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        let Some(dialect) = template_macro_dialect(node) else {
            visit::visit_expr_macro(self, node);
            return;
        };
        let root = parse_markup_tokens(dialect, node.mac.tokens.clone());
        if let Ok(root) = root {
            for child in &root.nodes {
                self.visit_template_node(child);
            }
        }
        visit::visit_expr_macro(self, node);
    }
}

fn attr_value_impl_self_name(item_impl: &ItemImpl) -> Option<String> {
    let Some((_, trait_path, _)) = &item_impl.trait_ else {
        return None;
    };
    if !is_attr_value_trait(trait_path) {
        return None;
    }

    type_path_last_ident(&item_impl.self_ty)
}

fn attr_value_impl_is_boolean_wrapper(item_impl: &ItemImpl) -> bool {
    let mut returns_boolean_attr = false;
    let mut renders_empty_value = false;

    for item in &item_impl.items {
        let ImplItem::Fn(method) = item else {
            continue;
        };
        match method.sig.ident.to_string().as_str() {
            "is_boolean_attr" => {
                returns_boolean_attr = block_returns_bool_literal(&method.block, true);
            }
            "render_attr_value" => {
                renders_empty_value = block_returns_ok_unit(&method.block);
            }
            _ => {}
        }
    }

    returns_boolean_attr && renders_empty_value
}

