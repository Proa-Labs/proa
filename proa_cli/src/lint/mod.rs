fn check_direct_helper_perf(
    path: &Path,
    render_block: &Block,
    helpers: &HelperIndex<'_>,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
    html: bool,
) {
    let mut visited = HashSet::new();
    check_direct_helper_perf_inner(
        path,
        render_block,
        helpers,
        suppressions,
        ignored_ranges,
        diagnostics,
        html,
        &mut visited,
    );
}

#[allow(clippy::too_many_arguments)]
fn check_direct_helper_perf_inner(
    path: &Path,
    block: &Block,
    helpers: &HelperIndex<'_>,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
    html: bool,
    visited: &mut HashSet<String>,
) {
    for helper_call in DirectHelperCalls::collect(block) {
        let Some(helper) = helpers.get(&helper_call.name) else {
            continue;
        };
        if !visited.insert(helper_call.name.clone()) {
            continue;
        }
        let line = helper.block.brace_token.span.open().start().line;
        if line_in_ranges(line, ignored_ranges) {
            continue;
        }
        if html {
            check_manual_escape_helper_perf(path, &helper_call, helper, suppressions, diagnostics);
        }
        check_string_display_helper_perf(path, &helper_call, helper, suppressions, diagnostics);
        check_render_block_perf(path, helper.block, suppressions, diagnostics, html);
        check_direct_helper_perf_inner(
            path,
            helper.block,
            helpers,
            suppressions,
            ignored_ranges,
            diagnostics,
            html,
            visited,
        );
    }
}

struct DirectHelperCalls {
    calls: HashMap<String, proc_macro2::Span>,
}

struct DirectHelperCall {
    name: String,
    span: proc_macro2::Span,
}

impl DirectHelperCalls {
    fn collect(block: &Block) -> Vec<DirectHelperCall> {
        let mut collector = Self {
            calls: HashMap::new(),
        };
        collector.visit_block(block);
        collector
            .calls
            .into_iter()
            .map(|(name, span)| DirectHelperCall { name, span })
            .collect()
    }

    fn collect_template_macro(&mut self, node: &ExprMacro) {
        let Some(dialect) = template_macro_dialect(node) else {
            return;
        };
        let root = parse_markup_tokens(dialect, node.mac.tokens.clone());
        let Ok(root) = root else {
            return;
        };

        for node in &root.nodes {
            self.collect_template_node(node);
        }
    }

    fn collect_template_node(&mut self, node: &Node) {
        match node {
            Node::Element(el) => {
                for attr in &el.attrs {
                    if let Attribute::Dynamic { value, .. } = attr {
                        self.visit_expr(value);
                    }
                }
                for child in &el.children {
                    self.collect_template_node(child);
                }
            }
            Node::Fragment(children) => {
                for child in children {
                    self.collect_template_node(child);
                }
            }
            Node::Block(expr) => self.visit_expr(expr),
            Node::Text(_) | Node::Doctype(_) => {}
        }
    }
}

impl<'ast> Visit<'ast> for DirectHelperCalls {
    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if let Some(name) = direct_helper_call_name(node) {
            self.calls.entry(name).or_insert_with(|| node.span());
        }
        visit::visit_expr_call(self, node);
    }

    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        if template_macro_dialect(node).is_some() {
            self.collect_template_macro(node);
        } else {
            self.collect_macro_arg_exprs(node);
        }
        visit::visit_expr_macro(self, node);
    }
}

impl DirectHelperCalls {
    fn collect_macro_arg_exprs(&mut self, node: &ExprMacro) {
        let parser = Punctuated::<Expr, Token![,]>::parse_terminated;
        if let Ok(args) = parser.parse2(node.mac.tokens.clone()) {
            for arg in args {
                self.visit_expr(&arg);
            }
        }
    }
}

