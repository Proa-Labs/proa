use std::fs;
use std::path::Path;
use std::process::{Command, Output};

fn run_build(root: &Path, target: &Path, host: &str, exported: &Path) -> Output {
    Command::new(env!("CARGO_BIN_EXE_cargo-proa"))
        .current_dir(root)
        .env("CARGO_TARGET_DIR", target)
        .args([
            "build",
            "--root",
            root.to_str().unwrap(),
            "--profile",
            "dev",
            "-p",
            "proa_linked_build_fixture",
            "--bin",
            "proa_linked_build_fixture",
            "--target",
            host,
            "--features",
            "hydration",
            "--locked",
            "--offline",
            "--no-check",
            "--no-assets",
            "--artifact-out",
            exported.to_str().unwrap(),
        ])
        .output()
        .unwrap()
}

fn stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

fn linked_plan(output: &Output) -> String {
    stdout(output)
        .lines()
        .find_map(|line| line.strip_prefix("linked RSJS plan "))
        .and_then(|line| line.split_once(" for package ").map(|(plan, _)| plan))
        .unwrap_or_else(|| panic!("missing linked plan in:\n{}", stdout(output)))
        .to_string()
}

fn assert_success(output: &Output) {
    assert!(
        output.status.success(),
        "stdout:\n{}\nstderr:\n{}",
        stdout(output),
        String::from_utf8_lossy(&output.stderr)
    );
}

#[test]
fn cargo_proa_build_runs_the_exact_linked_binary_pipeline() {
    let temp = tempfile::tempdir().unwrap();
    fs::create_dir_all(temp.path().join("src")).unwrap();
    fs::write(
        temp.path().join("Cargo.toml"),
        "[package]\n\
         name = \"proa_linked_build_fixture\"\n\
         version = \"0.0.0\"\n\
         edition = \"2021\"\n\n\
         [workspace]\n\n\
         [features]\n\
         hydration = []\n",
    )
    .unwrap();
    fs::write(
        temp.path().join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n\
         # It is not intended for manual editing.\n\
         version = 4\n\n\
         [[package]]\n\
         name = \"proa_linked_build_fixture\"\n\
         version = \"0.0.0\"\n",
    )
    .unwrap();
    fs::write(
        temp.path().join("src/main.rs"),
        "fn main() { println!(\"linked\"); }\n",
    )
    .unwrap();

    let rustc = std::env::var_os("RUSTC").unwrap_or_else(|| "rustc".into());
    let version = Command::new(rustc).arg("-vV").output().unwrap();
    assert!(version.status.success());
    let host = String::from_utf8(version.stdout)
        .unwrap()
        .lines()
        .find_map(|line| line.strip_prefix("host: "))
        .unwrap()
        .to_string();
    let target = temp.path().join("outer-target");
    // Keep exported artifacts under Cargo's excluded target tree. Exporting
    // into the package source closure would itself invalidate the next
    // descriptor build and turn this into a self-modifying fixture.
    let exported = target.join("dist/proa_linked_build_fixture");
    let first = run_build(temp.path(), &target, &host, &exported);
    assert_success(&first);
    let first_stdout = stdout(&first);
    assert!(first_stdout.contains("linked RSJS plan"), "{first_stdout}");
    assert!(
        first_stdout.contains("proa_linked_build_fixture"),
        "{first_stdout}"
    );
    assert!(
        first_stdout.contains("final Cargo artifacts:"),
        "{first_stdout}"
    );
    assert!(
        first_stdout.contains("exported linked RSJS executable"),
        "{first_stdout}"
    );
    assert!(
        first_stdout.contains(
            "linked RSJS build cache: descriptor 0/1 Cargo artifacts reused; final 0/1 reused"
        ),
        "{first_stdout}"
    );
    let first_plan = linked_plan(&first);

    let launched = Command::new(&exported).output().unwrap();
    assert!(launched.status.success());
    assert_eq!(launched.stdout, b"linked\n");

    let unchanged = run_build(temp.path(), &target, &host, &exported);
    assert_success(&unchanged);
    let unchanged_stdout = stdout(&unchanged);
    assert!(
        unchanged_stdout.contains(
            "linked RSJS build cache: descriptor 1/1 Cargo artifacts reused; final 1/1 reused"
        ),
        "{unchanged_stdout}"
    );
    assert_eq!(linked_plan(&unchanged), first_plan);
    let unchanged_launch = Command::new(&exported).output().unwrap();
    assert!(unchanged_launch.status.success());
    assert_eq!(unchanged_launch.stdout, b"linked\n");

    fs::write(
        temp.path().join("src/main.rs"),
        "fn main() { println!(\"source changed\"); }\n",
    )
    .unwrap();
    let source_changed = run_build(temp.path(), &target, &host, &exported);
    assert_success(&source_changed);
    let changed_stdout = stdout(&source_changed);
    assert!(
        changed_stdout.contains(
            "linked RSJS build cache: descriptor 0/1 Cargo artifacts reused; final 0/1 reused"
        ),
        "{changed_stdout}"
    );
    let changed_plan = linked_plan(&source_changed);
    assert_ne!(changed_plan, first_plan);
    let changed_launch = Command::new(&exported).output().unwrap();
    assert!(changed_launch.status.success());
    assert_eq!(changed_launch.stdout, b"source changed\n");

    let changed_unchanged = run_build(temp.path(), &target, &host, &exported);
    assert_success(&changed_unchanged);
    let changed_unchanged_stdout = stdout(&changed_unchanged);
    assert!(
        changed_unchanged_stdout.contains(
            "linked RSJS build cache: descriptor 1/1 Cargo artifacts reused; final 1/1 reused"
        ),
        "{changed_unchanged_stdout}"
    );
    assert_eq!(linked_plan(&changed_unchanged), changed_plan);
    let changed_unchanged_launch = Command::new(&exported).output().unwrap();
    assert!(changed_unchanged_launch.status.success());
    assert_eq!(changed_unchanged_launch.stdout, b"source changed\n");
}
