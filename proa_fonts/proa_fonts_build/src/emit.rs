//! Rust source generation: emit the `const FONT: Font = …` module that a crate
//! commits and references. The output targets [`proa_fonts`]'s public types and
//! is `rustfmt`-skipped so regeneration is byte-stable.

use std::fmt::Write as _;

use proa_fonts::{FontFormat, FontStyle, FontWeight};

use crate::ResolvedFace;

/// The pieces of a generated font that the emitted module needs. Borrowed so
/// the orchestrator can build the module string without moving its results.
pub struct ModuleView<'a> {
    pub const_name: &'a str,
    pub family: &'a str,
    pub class_name: &'a str,
    pub variable: &'a str,
    pub family_stack: &'a str,
    pub faces: &'a [ResolvedFace],
    pub css: &'a str,
}

/// Emit a complete standalone single-font `@generated` module: a per-font
/// banner, the `use`, and the font's items.
pub fn module(view: &ModuleView<'_>) -> String {
    let mut out = String::new();
    let _ = write!(
        out,
        "// @generated by proa_fonts_build - do not edit by hand.\n\
         //\n\
         // {family}: {n} face(s), self-hosted with a metric-matched fallback.\n\
         // Regenerate with `cargo proa font sync`.\n\
         #![cfg_attr(rustfmt, rustfmt::skip)]\n\
         \n\
         use proa_fonts::{{Font, FontFace, FontFormat, FontStyle, FontWeight}};\n\
         \n",
        family = view.family,
        n = view.faces.len(),
    );
    out.push_str(&items(view));
    out
}

/// The shared header for a multi-font generated file (the build collector
/// path): one `@generated` banner and one `use`, followed by many [`items`].
///
/// No inner `#![...]` attribute: this file is `include!`d into a module, where
/// inner attributes are not permitted. It lives in `OUT_DIR` and is never
/// hand-edited or formatted, so `rustfmt::skip` is unnecessary.
pub fn file_header() -> String {
    "// @generated by proa_fonts_build - do not edit by hand.\n\
     use proa_fonts::{Font, FontFace, FontFormat, FontStyle, FontWeight};\n\
     \n"
    .to_string()
}

/// Emit just one font's items (doc comment, `pub const`, faces, css). No
/// header or `use`, so many fonts can share a single generated file.
pub fn items(view: &ModuleView<'_>) -> String {
    let c = view.const_name;
    let mut out = String::new();

    let _ = write!(
        out,
        "/// `{family}`, self-hosted with a metric-matched fallback. See [`proa_fonts`].\n\
         pub const {c}: Font = Font {{\n\
         \x20   family: {family_lit},\n\
         \x20   class_name: {class_lit},\n\
         \x20   variable: {variable_lit},\n\
         \x20   family_stack: {stack_lit},\n\
         \x20   faces: {c}_FACES,\n\
         \x20   css: {c}_CSS,\n\
         }};\n\
         \n\
         const {c}_FACES: &[FontFace] = &[\n",
        family = view.family,
        family_lit = rust_str(view.family),
        class_lit = rust_str(view.class_name),
        variable_lit = rust_str(view.variable),
        stack_lit = rust_str(view.family_stack),
    );

    for face in view.faces {
        let _ = writeln!(
            out,
            "    FontFace {{ url: {url}, format: {format}, weight: {weight}, style: {style}, preload: {preload} }},",
            url = rust_str(&face.url),
            format = format_lit(face.format),
            weight = weight_lit(face.weight),
            style = style_lit(face.style),
            preload = face.preload,
        );
    }

    let _ = writeln!(
        out,
        "];\n\nconst {c}_CSS: &str = {css};",
        css = rust_str(view.css),
    );

    out
}

fn format_lit(format: FontFormat) -> &'static str {
    match format {
        FontFormat::Woff2 => "FontFormat::Woff2",
        FontFormat::Truetype => "FontFormat::Truetype",
        FontFormat::Opentype => "FontFormat::Opentype",
    }
}

fn style_lit(style: FontStyle) -> &'static str {
    match style {
        FontStyle::Normal => "FontStyle::Normal",
        FontStyle::Italic => "FontStyle::Italic",
    }
}

fn weight_lit(weight: FontWeight) -> String {
    match weight {
        FontWeight::Fixed(w) => format!("FontWeight::Fixed({w})"),
        FontWeight::Variable { min, max } => {
            format!("FontWeight::Variable {{ min: {min}, max: {max} }}")
        }
    }
}

/// Render `s` as an escaped Rust double-quoted string literal.
fn rust_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn face(url: &str, preload: bool, style: FontStyle, weight: FontWeight) -> ResolvedFace {
        ResolvedFace {
            filename: url.rsplit('/').next().unwrap().to_string(),
            url: url.to_string(),
            sha256_hex: "deadbeef".to_string(),
            format: FontFormat::Woff2,
            weight,
            style,
            display: proa_fonts::FontDisplay::Swap,
            unicode_range: None,
            preload,
            bytes: Vec::new(),
        }
    }

    #[test]
    fn emits_a_stable_module() {
        let faces = vec![
            face(
                "/fonts/geist-latin-400-normal.9f2c1a3b.woff2",
                true,
                FontStyle::Normal,
                FontWeight::Fixed(400),
            ),
            face(
                "/fonts/geist-latin-400-italic.7a1b2c3d.woff2",
                false,
                FontStyle::Italic,
                FontWeight::Fixed(400),
            ),
        ];
        let view = ModuleView {
            const_name: "GEIST",
            family: "Geist",
            class_name: "__proa_font_geist_9f2c1a3b",
            variable: "--font-geist",
            family_stack: "'Geist','Geist Fallback',system-ui,sans-serif",
            faces: &faces,
            css: "@font-face{font-family:'Geist'}\n:root{--font-geist:'Geist'}",
        };

        let src = module(&view);
        let expected = "\
// @generated by proa_fonts_build - do not edit by hand.
//
// Geist: 2 face(s), self-hosted with a metric-matched fallback.
// Regenerate with `cargo proa font sync`.
#![cfg_attr(rustfmt, rustfmt::skip)]

use proa_fonts::{Font, FontFace, FontFormat, FontStyle, FontWeight};

/// `Geist`, self-hosted with a metric-matched fallback. See [`proa_fonts`].
pub const GEIST: Font = Font {
    family: \"Geist\",
    class_name: \"__proa_font_geist_9f2c1a3b\",
    variable: \"--font-geist\",
    family_stack: \"'Geist','Geist Fallback',system-ui,sans-serif\",
    faces: GEIST_FACES,
    css: GEIST_CSS,
};

const GEIST_FACES: &[FontFace] = &[
    FontFace { url: \"/fonts/geist-latin-400-normal.9f2c1a3b.woff2\", format: FontFormat::Woff2, weight: FontWeight::Fixed(400), style: FontStyle::Normal, preload: true },
    FontFace { url: \"/fonts/geist-latin-400-italic.7a1b2c3d.woff2\", format: FontFormat::Woff2, weight: FontWeight::Fixed(400), style: FontStyle::Italic, preload: false },
];

const GEIST_CSS: &str = \"@font-face{font-family:'Geist'}\\n:root{--font-geist:'Geist'}\";
";
        assert_eq!(src, expected);
    }

    #[test]
    fn escapes_variable_font_weight() {
        assert_eq!(
            weight_lit(FontWeight::Variable { min: 100, max: 900 }),
            "FontWeight::Variable { min: 100, max: 900 }"
        );
    }

    #[test]
    fn rust_str_escapes_specials() {
        assert_eq!(rust_str("a\"b\\c\nd"), "\"a\\\"b\\\\c\\nd\"");
    }
}
