use std::collections::HashMap;
use std::string::String;

use proa_core::{ctx::Ctx, text::UnsafeRaw, WebRenderSync, WriteError};
use proa_macros::html_sync;

use crate::js::quote_js;
use crate::{DEFAULT_REACT_DOM_URL, DEFAULT_REACT_URL};

/// The bootstrap JS template, embedded at compile time.
const BOOTSTRAP_TEMPLATE: &str = include_str!("../js/bootstrap.js");

/// Hydration behaviour for a React island.
#[derive(Clone, Copy, Debug)]
pub enum HydrationStrategy<'a> {
    /// Hydrate immediately during boot.
    Immediate,
    /// Hydrate during the next idle period (falls back to `setTimeout`).
    Idle,
    /// Hydrate once the island becomes visible in the viewport.
    Visible,
    /// Hydrate after a specific DOM event fires on the island container.
    Interaction { event: &'a str },
    /// Hydrate once a media query matches.
    Media { query: &'a str },
}

impl<'a> HydrationStrategy<'a> {
    fn as_js(&self) -> String {
        match self {
            HydrationStrategy::Immediate => r#"{ type: "immediate" }"#.to_string(),
            HydrationStrategy::Idle => r#"{ type: "idle" }"#.to_string(),
            HydrationStrategy::Visible => r#"{ type: "visible" }"#.to_string(),
            HydrationStrategy::Interaction { event } => {
                format!(r#"{{ type: "interaction", event: {} }}"#, quote_js(event))
            }
            HydrationStrategy::Media { query } => {
                format!(r#"{{ type: "media", query: {} }}"#, quote_js(query))
            }
        }
    }
}

/// Metadata describing how to load a client-side React component.
#[derive(Clone, Copy, Debug)]
pub struct ReactModuleDescriptor<'a> {
    /// The island identifier rendered on the server (`data-island`).
    pub island: &'a str,
    /// Dynamic import path for the React component module.
    pub module_path: &'a str,
    /// Optional named export to use from the module (`default` when omitted).
    pub export: Option<&'a str>,
    /// Hydration trigger strategy.
    pub strategy: HydrationStrategy<'a>,
}

/// Options for rendering the default hydration bootstrap.
#[derive(Clone, Copy, Debug)]
pub struct ReactBootstrapConfig<'a> {
    /// Selector used to discover islands.
    pub selector: &'a str,
    /// Module specifier for React (used in the inline bootstrap).
    pub react_import: &'a str,
    /// Module specifier providing `hydrateRoot`.
    pub react_dom_client_import: &'a str,
    /// Name of the hydrate function to import (defaults to `hydrateRoot`).
    pub hydrate_fn: &'a str,
    /// Whether to invoke hydration immediately after the script runs.
    pub auto_run: bool,
    /// Optional global exposed on `window` to trigger hydration manually.
    pub expose_global: Option<&'a str>,
    /// Whether to use external React runtime via import map (enables cross-page caching).
    pub use_external_runtime: bool,
    /// URL for external React module (only used when use_external_runtime = true).
    pub react_module_url: &'a str,
    /// URL for external ReactDOM client module (only used when use_external_runtime = true).
    pub react_dom_module_url: &'a str,
}

impl<'a> Default for ReactBootstrapConfig<'a> {
    fn default() -> Self {
        Self {
            selector: "[data-island]",
            react_import: "react",
            react_dom_client_import: "react-dom/client",
            hydrate_fn: "hydrateRoot",
            auto_run: true,
            expose_global: Some("__proaHydrateIslands"),
            // Use external runtime by default for cross-page caching
            // URLs are auto-generated from package.json by build.rs
            use_external_runtime: true,
            react_module_url: DEFAULT_REACT_URL,
            react_dom_module_url: DEFAULT_REACT_DOM_URL,
        }
    }
}

/// A React bootstrap script that implements `Render`.
#[derive(Clone, Debug)]
pub struct ReactBootstrap {
    script: String,
}

// proa-perf-ok(scope): the script is generated by Proa's bootstrap builder;
// UnsafeRaw avoids escaping JavaScript source inside script raw text
impl WebRenderSync for ReactBootstrap {
    fn render(self, cx: &mut Ctx) -> Result<(), WriteError> {
        let nonce = cx.csp_nonce_cloned();
        html_sync! {
            <script type="module" nonce={proa_core::csp_nonce_attr(nonce.as_ref())}>
                {UnsafeRaw(&self.script)}
            </script>
        }
        .render(cx)
    }
}

/// Creates a React bootstrap script that can be rendered later.
pub fn react_bootstrap(
    descriptors: &[ReactModuleDescriptor<'_>],
    config: &ReactBootstrapConfig<'_>,
) -> ReactBootstrap {
    ReactBootstrap {
        script: build_bootstrap_script(descriptors, config),
    }
}

/// **Deprecated**: Use `react_bootstrap` which returns a `ReactBootstrap` type instead.
pub fn render_react_bootstrap(
    cx: &mut Ctx,
    descriptors: &[ReactModuleDescriptor<'_>],
    config: &ReactBootstrapConfig<'_>,
) -> Result<(), WriteError> {
    // If external runtime is enabled, inject import map first
    if config.use_external_runtime {
        render_react_import_map(cx, config)?;
    }

    react_bootstrap(descriptors, config).render(cx)
}

/// Renders an import map for external React runtime using hardcoded React URLs from config.
/// This enables cross-page caching of React modules.
/// Used as a fallback when the manifest doesn't contain an import map.
// proa-perf-ok(scope): every import-map key and URL is JSON-encoded before
// trusted JSON is emitted into script raw text
pub fn render_react_import_map(
    cx: &mut Ctx,
    config: &ReactBootstrapConfig<'_>,
) -> Result<(), WriteError> {
    use std::fmt::Write;

    let mut import_map = String::with_capacity(512);

    // Build import map JSON
    write!(&mut import_map, "{{").unwrap();
    write!(&mut import_map, r#""imports":{{"#).unwrap();
    // JSON-escape all import map keys and values to prevent injection
    write!(
        &mut import_map,
        "{}:{},",
        serde_json::to_string(config.react_import).unwrap(),
        serde_json::to_string(config.react_module_url).unwrap(),
    )
    .unwrap();
    // react/jsx-runtime is required for the modern JSX transform (React 17+)
    // Derive the URL from the react module URL (e.g. esm.sh/react@19/jsx-runtime)
    let jsx_runtime_url = config
        .react_module_url
        .find('?')
        .map(|q| {
            format!(
                "{}/jsx-runtime{}",
                &config.react_module_url[..q],
                &config.react_module_url[q..]
            )
        })
        .unwrap_or_else(|| format!("{}/jsx-runtime", config.react_module_url));
    write!(
        &mut import_map,
        "\"react/jsx-runtime\":{},",
        serde_json::to_string(jsx_runtime_url.as_str()).unwrap(),
    )
    .unwrap();
    // react-dom bare specifier (some libraries import from "react-dom" directly)
    let react_dom_url = config.react_dom_module_url.replace("/client", "");
    write!(
        &mut import_map,
        "\"react-dom\":{},",
        serde_json::to_string(react_dom_url.as_str()).unwrap(),
    )
    .unwrap();
    write!(
        &mut import_map,
        "{}:{}",
        serde_json::to_string(config.react_dom_client_import).unwrap(),
        serde_json::to_string(config.react_dom_module_url).unwrap(),
    )
    .unwrap();
    write!(&mut import_map, r#"}}}}"#).unwrap();

    let nonce = cx.csp_nonce_cloned();
    html_sync! {
        <script type="importmap" nonce={proa_core::csp_nonce_attr(nonce.as_ref())}>
            {UnsafeRaw(&import_map)}
        </script>
    }
    .render(cx)
}

/// Renders a `<script type="importmap">` tag from arbitrary specifier→URL entries.
/// Entries are sorted by key for deterministic output.
// proa-perf-ok(scope): every caller-supplied key and URL is JSON-encoded before
// trusted JSON is emitted into script raw text
pub fn render_import_map_entries(
    cx: &mut Ctx,
    entries: &HashMap<String, String>,
) -> Result<(), WriteError> {
    use std::fmt::Write;

    let mut import_map = String::with_capacity(512);

    // Sort entries for deterministic output
    let mut sorted: Vec<_> = entries.iter().collect();
    sorted.sort_by_key(|(k, _)| k.as_str());

    write!(&mut import_map, "{{").unwrap();
    write!(&mut import_map, r#""imports":{{"#).unwrap();

    for (i, (specifier, url)) in sorted.iter().enumerate() {
        if i > 0 {
            import_map.push(',');
        }
        // JSON-escape keys and values to prevent injection
        let safe_key = serde_json::to_string(specifier.as_str()).unwrap();
        let safe_val = serde_json::to_string(url.as_str()).unwrap();
        write!(&mut import_map, "{}:{}", safe_key, safe_val).unwrap();
    }

    write!(&mut import_map, r#"}}}}"#).unwrap();

    let nonce = cx.csp_nonce_cloned();
    html_sync! {
        <script type="importmap" nonce={proa_core::csp_nonce_attr(nonce.as_ref())}>
            {UnsafeRaw(&import_map)}
        </script>
    }
    .render(cx)
}

/// Validate that a string is a safe JavaScript identifier (ASCII alphanumeric,
/// underscore, or `$`, not starting with a digit). Used to guard values that
/// are interpolated into JS identifier positions rather than string literals.
fn is_valid_js_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        None => false,
        Some(c) if !(c.is_ascii_alphabetic() || c == '_' || c == '$') => false,
        _ => chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$'),
    }
}

fn build_bootstrap_script(
    descriptors: &[ReactModuleDescriptor<'_>],
    config: &ReactBootstrapConfig<'_>,
) -> String {
    // hydrate_fn is interpolated as a raw JS identifier (import name + call
    // site). Reject anything that isn't a valid identifier to prevent
    // injection of arbitrary JS.
    assert!(
        is_valid_js_identifier(config.hydrate_fn),
        "ReactBootstrapConfig::hydrate_fn must be a valid JavaScript identifier, got: {:?}",
        config.hydrate_fn
    );

    // Build imports
    let imports = format!(
        "import React from {};\nimport {{ {} }} from {};",
        quote_js(config.react_import),
        config.hydrate_fn,
        quote_js(config.react_dom_client_import),
    );

    // Build registry entries
    let mut registry = String::new();
    for desc in descriptors {
        registry.push_str("  [");
        registry.push_str(&quote_js(desc.island));
        registry.push_str(", { modulePath: ");
        registry.push_str(&quote_js(desc.module_path));
        registry.push_str(", exportName: ");
        if let Some(export) = desc.export {
            registry.push_str(&quote_js(export));
        } else {
            registry.push_str("null");
        }
        registry.push_str(", strategy: ");
        registry.push_str(&desc.strategy.as_js());
        registry.push_str(" }],\n");
    }

    // Build mount call (store root for Turbo Drive cleanup)
    let mount = if config.hydrate_fn == "createRoot" {
        "const root = createRoot(el); root.render(element); roots.set(el.id, root);".to_string()
    } else {
        format!(
            "const root = {}(el, element); roots.set(el.id, root);",
            config.hydrate_fn
        )
    };

    // Build footer
    let mut footer = String::new();
    // Always expose __proa namespace for Turbo Drive bridge
    footer.push_str("window.__proa = { hydrateIslands, unmountAll };\n");
    if let Some(global_name) = config.expose_global {
        footer.push_str(&format!(
            "window[{}] = hydrateIslands;\n",
            quote_js(global_name)
        ));
    }
    if config.auto_run {
        footer.push_str("hydrateIslands();");
    }

    // Single template with 5 replacements
    BOOTSTRAP_TEMPLATE
        .replace("/*__PROA_IMPORTS__*/", &imports)
        .replace("/*__PROA_REGISTRY__*/", &registry)
        .replace("/*__PROA_SELECTOR__*/", &quote_js(config.selector))
        .replace("/*__PROA_MOUNT__*/", &mount)
        .replace("/*__PROA_FOOTER__*/", &footer)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bootstrap_renders_registry_and_defaults() {
        let mut cx = Ctx::new();
        render_react_bootstrap(
            &mut cx,
            &[ReactModuleDescriptor {
                island: "UserCard",
                module_path: "/static/UserCard.js",
                export: Some("UserCard"),
                strategy: HydrationStrategy::Interaction { event: "click" },
            }],
            &ReactBootstrapConfig::default(),
        )
        .unwrap();
        let html = String::from_utf8(cx.into_output().into_vec()).unwrap();
        assert!(
            html.contains("modulePath: \"/static/UserCard.js\""),
            "bootstrap should embed module path"
        );
        assert!(html.contains("React.createElement"), "should import React");
        assert!(
            html.contains("requestIdleCallback"),
            "should include idle fallback logic"
        );
    }

    #[test]
    fn bootstrap_and_import_map_use_request_nonce() {
        let nonce = proa_core::CspNonce::new("reactNonce123").unwrap();
        let mut cx = Ctx::new().with_csp_nonce(nonce);
        render_react_bootstrap(
            &mut cx,
            &[ReactModuleDescriptor {
                island: "UserCard",
                module_path: "/static/UserCard.js",
                export: None,
                strategy: HydrationStrategy::Immediate,
            }],
            &ReactBootstrapConfig::default(),
        )
        .unwrap();
        let html = String::from_utf8(cx.into_output().into_vec()).unwrap();
        assert_eq!(html.matches("<script").count(), 2);
        assert_eq!(html.matches(r#"nonce="reactNonce123""#).count(), 2);
        assert!(
            html.contains(r#"<script type="importmap" nonce="reactNonce123">"#),
            "{html}"
        );
        assert!(
            html.contains(r#"<script type="module" nonce="reactNonce123">"#),
            "{html}"
        );
    }

    #[test]
    fn bootstrap_renders_media_strategy() {
        let mut cx = Ctx::new();
        render_react_bootstrap(
            &mut cx,
            &[ReactModuleDescriptor {
                island: "HeroChart",
                module_path: "/static/HeroChart.js",
                export: None,
                strategy: HydrationStrategy::Media {
                    query: "(min-width: 768px)",
                },
            }],
            &ReactBootstrapConfig::default(),
        )
        .unwrap();
        let html = String::from_utf8(cx.into_output().into_vec()).unwrap();
        assert!(
            html.contains(r#"strategy: { type: "media", query: "(min-width: 768px)" }"#),
            "bootstrap should embed media strategy config, got:\n{html}"
        );
        assert!(
            html.contains("matchMedia"),
            "bootstrap should include media scheduling logic"
        );
    }
}
