fn direct_helper_call_name(call: &ExprCall) -> Option<String> {
    let Expr::Path(path) = call.func.as_ref() else {
        return None;
    };
    if path.path.segments.len() != 1 {
        return None;
    }
    let name = path.path.segments.first()?.ident.to_string();
    if matches!(
        name.as_str(),
        "Ok" | "Err" | "Some" | "None" | "Box" | "Vec" | "String" | "perf_ok"
    ) {
        return None;
    }
    Some(name)
}

pub(crate) fn parse_invocation(source: &str, inv: &MacroInvocation) -> syn::Result<HtmlRoot> {
    let body = inv.body(source);
    let tokens = TokenStream::from_str(body)
        .map_err(|err| syn::Error::new(proc_macro2::Span::call_site(), err.to_string()))?;
    parse_markup_tokens(inv.dialect, tokens)
}

/// Parse macro tokens into the markup tree shared by the HTML and XML dialects.
///
/// `md!` / `md_sync!` bodies are a single string literal rather than a markup
/// tree, so they never parse here. Callers that handle Markdown branch on the
/// dialect first; the rest treat the error as "nothing to lint", which is
/// exactly right for a template with no elements.
pub(crate) fn parse_markup_tokens(
    dialect: MacroDialect,
    tokens: TokenStream,
) -> syn::Result<HtmlRoot> {
    match dialect {
        MacroDialect::Html => syn::parse2::<HtmlRoot>(tokens),
        MacroDialect::Xml => syn::parse2::<XmlRoot>(tokens).map(XmlRoot::into_inner),
        MacroDialect::Md => Err(syn::Error::new(
            proc_macro2::Span::call_site(),
            "markdown templates have no markup tree",
        )),
    }
}

fn parse_error_diag(path: &Path, inv: &MacroInvocation, err: syn::Error) -> Diagnostic {
    let pos =
        file_line_column_for_body_span(inv, err.span()).unwrap_or(crate::source::LineColumn {
            line: inv.name_line,
            column: inv.name_column,
        });
    Diagnostic::new(
        path,
        pos.line,
        pos.column + 1,
        Severity::Error,
        "parse/template",
        format!("failed to parse {}! macro body: {err}", inv.name),
    )
}

fn lint_indentation(
    path: &Path,
    inv: &MacroInvocation,
    root: &HtmlRoot,
    diagnostics: &mut Vec<Diagnostic>,
) {
    for node in &root.nodes {
        lint_node_indentation(path, inv, node, diagnostics);
    }
}

fn lint_node_indentation(
    path: &Path,
    inv: &MacroInvocation,
    node: &Node,
    diagnostics: &mut Vec<Diagnostic>,
) {
    match node {
        Node::Element(el) => {
            validate_element_indentation(path, inv, el, diagnostics);
            for child in &el.children {
                lint_node_indentation(path, inv, child, diagnostics);
            }
        }
        Node::Fragment(children) => {
            for child in children {
                lint_node_indentation(path, inv, child, diagnostics);
            }
        }
        Node::Text(_) | Node::Block(_) | Node::Doctype(_) => {}
    }
}

fn validate_element_indentation(
    path: &Path,
    inv: &MacroInvocation,
    el: &Element,
    diagnostics: &mut Vec<Diagnostic>,
) {
    let parent_pos = el.name.start_line_column();
    let opening_end_pos = el.opening_end_line_column();
    if parent_pos.line == 0 || opening_end_pos.line == 0 {
        return;
    }

    for child in &el.children {
        validate_child_indentation(
            path,
            inv,
            &el.tag_str(),
            parent_pos,
            opening_end_pos,
            child,
            diagnostics,
        );
    }
}

fn validate_child_indentation(
    path: &Path,
    inv: &MacroInvocation,
    parent_tag: &str,
    parent_pos: LineColumn,
    parent_opening_end_pos: LineColumn,
    child: &Node,
    diagnostics: &mut Vec<Diagnostic>,
) {
    match child {
        Node::Element(child_el) => {
            let child_pos = child_el.name.start_line_column();
            if child_pos.line > parent_opening_end_pos.line && child_pos.column == parent_pos.column
            {
                let file_pos = file_line_column_for_body_span(inv, child_el.name.span()).unwrap_or(
                    crate::source::LineColumn {
                        line: inv.name_line,
                        column: inv.name_column,
                    },
                );
                diagnostics.push(
                    Diagnostic::new(
                        path,
                        file_pos.line,
                        file_pos.column + 1,
                        Severity::Warning,
                        "format/indentation",
                        format!(
                            "`<{child}>` is not indented deeper than its parent `<{parent_tag}>`",
                            child = child_el.tag_str()
                        ),
                    )
                    .with_help(
                        "run `cargo proa fmt` or indent nested markup deeper than its parent",
                    ),
                );
            }
        }
        Node::Fragment(children) => {
            for child in children {
                validate_child_indentation(
                    path,
                    inv,
                    parent_tag,
                    parent_pos,
                    parent_opening_end_pos,
                    child,
                    diagnostics,
                );
            }
        }
        Node::Text(_) | Node::Block(_) | Node::Doctype(_) => {}
    }
}

fn lint_perf(
    path: &Path,
    inv: &MacroInvocation,
    root: &HtmlRoot,
    in_rsjs_item: bool,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    for node in &root.nodes {
        lint_node_perf(
            path,
            inv,
            node,
            None,
            in_rsjs_item,
            suppressions,
            diagnostics,
        );
    }
}

fn lint_node_perf(
    path: &Path,
    inv: &MacroInvocation,
    node: &Node,
    parent_tag: Option<&str>,
    in_rsjs_item: bool,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    match node {
        Node::Element(el) => {
            lint_element_correctness(
                path,
                inv,
                el,
                parent_tag,
                in_rsjs_item,
                suppressions,
                diagnostics,
            );
            let tag = el.tag_str();
            for child in &el.children {
                if let Node::Block(expr) = child {
                    if !is_perf_suppressed(expr)
                        && matches!(expr, Expr::Lit(lit) if matches!(lit.lit, syn::Lit::Str(_)))
                    {
                        push_expr_diag(
                            path,
                            SpanOrigin::Macro(inv),
                            diagnostics,
                            suppressions,
                            expr.span(),
                            "perf/static-fragment-value",
                            "static text is hidden inside a runtime expression block",
                            "write the text as a literal node so Proa can consolidate it statically",
                        );
                        push_expr_diag(
                            path,
                            SpanOrigin::Macro(inv),
                            diagnostics,
                            suppressions,
                            expr.span(),
                            "perf/braced-string-literal",
                            "string literal in `{...}` is runtime escaped",
                            "use a text node like `\"text\"` so Proa can escape it at compile time",
                        );
                    }
                    check_expr_perf(
                        path,
                        SpanOrigin::Macro(inv),
                        expr,
                        suppressions,
                        diagnostics,
                    );
                }
                lint_node_perf(
                    path,
                    inv,
                    child,
                    Some(&tag),
                    in_rsjs_item,
                    suppressions,
                    diagnostics,
                );
            }

            for attr in &el.attrs {
                lint_attr_perf(path, inv, attr, suppressions, diagnostics);
            }
        }
        Node::Fragment(children) => {
            for child in children {
                lint_node_perf(
                    path,
                    inv,
                    child,
                    parent_tag,
                    in_rsjs_item,
                    suppressions,
                    diagnostics,
                );
            }
        }
        Node::Block(expr) => {
            check_expr_perf(
                path,
                SpanOrigin::Macro(inv),
                expr,
                suppressions,
                diagnostics,
            );
        }
        Node::Text(_) | Node::Doctype(_) => {}
    }
}

fn lint_template_accessibility(
    path: &Path,
    inv: &MacroInvocation,
    root: &HtmlRoot,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    let mut listboxes = Vec::new();
    let mut controlled_ids = HashSet::new();
    for node in &root.nodes {
        collect_listbox_accessibility(node, &mut listboxes, &mut controlled_ids);
    }

    for listbox in listboxes {
        if listbox.focusable
            || listbox.has_active_descendant
            || listbox
                .id
                .as_deref()
                .is_some_and(|id| controlled_ids.contains(id))
        {
            continue;
        }

        push_expr_diag_with_severity(
            path,
            SpanOrigin::Macro(inv),
            diagnostics,
            suppressions,
            listbox.span,
            Severity::Info,
            "a11y/listbox-control",
            "`role=\"listbox\"` is not statically associated with a keyboard controller",
            "add `aria-controls` on the input/button that controls this listbox, or make the listbox itself focusable with keyboard handling",
        );
    }
}

struct ListboxAccessibility {
    span: proc_macro2::Span,
    id: Option<String>,
    focusable: bool,
    has_active_descendant: bool,
}

fn collect_listbox_accessibility(
    node: &Node,
    listboxes: &mut Vec<ListboxAccessibility>,
    controlled_ids: &mut HashSet<String>,
) {
    match node {
        Node::Element(el) => {
            if let Some(id) = static_attr_value(el, "aria-controls") {
                controlled_ids.insert(id);
            }

            if static_attr_value(el, "role").as_deref() == Some("listbox") {
                listboxes.push(ListboxAccessibility {
                    span: el.name.span(),
                    id: static_attr_value(el, "id"),
                    focusable: static_attr_value(el, "tabindex").is_some()
                        || bool_attr_present(el, "tabindex"),
                    has_active_descendant: static_attr_value(el, "aria-activedescendant").is_some(),
                });
            }

            for child in &el.children {
                collect_listbox_accessibility(child, listboxes, controlled_ids);
            }
        }
        Node::Fragment(children) => {
            for child in children {
                collect_listbox_accessibility(child, listboxes, controlled_ids);
            }
        }
        Node::Text(_) | Node::Block(_) | Node::Doctype(_) => {}
    }
}

fn lint_element_correctness(
    path: &Path,
    inv: &MacroInvocation,
    el: &Element,
    parent_tag: Option<&str>,
    in_rsjs_item: bool,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    if parent_tag.is_some_and(|parent| invalid_parent_child_pair(parent, &el.tag_str())) {
        push_expr_diag(
            path,
            SpanOrigin::Macro(inv),
            diagnostics,
            suppressions,
            el.name.span(),
            "html/invalid-nesting",
            "statically visible HTML nesting is invalid or suspicious",
            "move the child to a valid parent or split the parent element before rendering this child",
        );
    }

    let mut seen = HashSet::new();
    for attr in &el.attrs {
        let name = attr_name(attr);
        if !seen.insert(name.as_markup_str().to_owned()) {
            push_expr_diag(
                path,
                SpanOrigin::Macro(inv),
                diagnostics,
                suppressions,
                name.span(),
                "attr/duplicate",
                "duplicate attribute on the same element",
                "remove the duplicate or combine the values before rendering",
            );
        }

        lint_attr_name_correctness(path, inv, name, in_rsjs_item, suppressions, diagnostics);
    }
}

fn lint_attr_name_correctness(
    path: &Path,
    inv: &MacroInvocation,
    name: &MarkupName,
    in_rsjs_item: bool,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    let raw = name.as_markup_str();
    if (raw.starts_with("data-") || raw.starts_with("aria-")) && !data_or_aria_name_is_valid(raw) {
        push_expr_diag(
            path,
            SpanOrigin::Macro(inv),
            diagnostics,
            suppressions,
            name.span(),
            "attr/data-name",
            "data-* or aria-* attribute name is malformed",
            "use lowercase dash-separated data-* / aria-* names with a non-empty suffix",
        );
    }

    if event_attr_name_is_suspicious(raw) && !(in_rsjs_item && rsjs_event_attr_name(raw)) {
        push_expr_diag(
            path,
            SpanOrigin::Macro(inv),
            diagnostics,
            suppressions,
            name.span(),
            "attr/event-name",
            "event-like attribute spelling is suspicious",
            "use the event spelling expected by the target renderer, for example `on:click` if using delegated events",
        );
    }
}

fn lint_attr_perf(
    path: &Path,
    inv: &MacroInvocation,
    attr: &Attribute,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    match attr {
        Attribute::Static { name, value } => {
            if attr_name_is(name, "class") && value.value().trim().is_empty() {
                push_expr_diag(
                    path,
                    SpanOrigin::Macro(inv),
                    diagnostics,
                    suppressions,
                    value.span(),
                    "perf/empty-class",
                    "empty class attributes add bytes without styling anything",
                    "remove `class=\"\"` or omit the class field when there are no classes",
                );
            }
        }
        Attribute::Dynamic { name, value } => {
            let value = value.as_ref();
            if is_perf_suppressed(value) {
                return;
            }

            if let Some(bool_value) = expr_bool_literal(value) {
                let (code, message, help) = if bool_value {
                    (
                        "perf/static-bool-attr",
                        "dynamic true boolean attribute breaks static consolidation",
                        "write the boolean attribute directly, for example `disabled`",
                    )
                } else {
                    (
                        "perf/false-bool-attr",
                        "dynamic false boolean attribute renders no useful static output",
                        "remove the attribute instead of writing `attr={false}`",
                    )
                };
                push_expr_diag(
                    path,
                    SpanOrigin::Macro(inv),
                    diagnostics,
                    suppressions,
                    value.span(),
                    code,
                    message,
                    help,
                );
            }

            if attr_name_is(name, "class") {
                lint_class_attr_perf(path, inv, value, suppressions, diagnostics);
            } else if attr_name_is(name, "style") {
                lint_style_attr_perf(path, inv, value, suppressions, diagnostics);
            } else if expr_string_literal(value).is_some() {
                push_expr_diag(
                    path,
                    SpanOrigin::Macro(inv),
                    diagnostics,
                    suppressions,
                    value.span(),
                    "perf/dynamic-literal-attr",
                    "dynamic attribute with a literal value breaks static consolidation",
                    "write `attr=\"value\"` instead of `attr={\"value\"}`",
                );
            }

            check_expr_perf(
                path,
                SpanOrigin::Macro(inv),
                value,
                suppressions,
                diagnostics,
            );
        }
        Attribute::Bool { .. } => {}
    }
}

fn lint_class_attr_perf(
    path: &Path,
    inv: &MacroInvocation,
    value: &Expr,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    if let Some(lit) = expr_string_literal(value) {
        if lit.value().trim().is_empty() {
            push_expr_diag(
                path,
                SpanOrigin::Macro(inv),
                diagnostics,
                suppressions,
                value.span(),
                "perf/empty-class",
                "empty class attributes add bytes without styling anything",
                "remove `class={\"\"}` or omit the class field when there are no classes",
            );
        } else {
            push_expr_diag(
                path,
                SpanOrigin::Macro(inv),
                diagnostics,
                suppressions,
                value.span(),
                "perf/dynamic-class-literal",
                "literal class strings in dynamic expressions break static consolidation",
                "write `class=\"...\"` so Proa can fold the class into the static byte run",
            );
        }
        return;
    }

    if expr_is_format_macro(value) {
        push_expr_diag(
            path,
            SpanOrigin::Macro(inv),
            diagnostics,
            suppressions,
            value.span(),
            "perf/class-format",
            "format!() in a class attribute allocates a String in the render path",
            "use ClassList, tw_join!, or precompute the class string outside render",
        );
        if format_macro_uses_only_static_fragments(value) {
            push_expr_diag(
                path,
                SpanOrigin::Macro(inv),
                diagnostics,
                suppressions,
                value.span(),
                "perf/runtime-tailwind",
                "static class fragments are being joined at runtime",
                "move static Tailwind fragments into a static class attribute or tw_join! constant",
            );
        }
    }

    if expr_is_join_call(value) {
        let (code, message, help) = if expr_contains_vec_macro(value) {
            (
                "perf/class-vec",
                "vec![...].join(\" \") in a class attribute allocates a Vec and String",
                "use ClassList or tw_join! for class composition",
            )
        } else {
            (
                "perf/class-join",
                ".join(\" \") in a class attribute allocates a String",
                "use ClassList for dynamic classes or tw_join! for static classes",
            )
        };
        push_expr_diag(
            path,
            SpanOrigin::Macro(inv),
            diagnostics,
            suppressions,
            value.span(),
            code,
            message,
            help,
        );
    }
}

fn lint_style_attr_perf(
    path: &Path,
    inv: &MacroInvocation,
    value: &Expr,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    if expr_string_literal(value).is_some() {
        push_expr_diag(
            path,
            SpanOrigin::Macro(inv),
            diagnostics,
            suppressions,
            value.span(),
            "perf/static-style-string",
            "literal style strings in dynamic expressions break static consolidation",
            "write `style=\"...\"` or prefer classes / typed style attributes",
        );
    }
    if format_macro_template_contains(value, "%") {
        push_expr_diag(
            path,
            SpanOrigin::Macro(inv),
            diagnostics,
            suppressions,
            value.span(),
            "perf/dynamic-style-percent",
            "runtime percentage style strings allocate and are hard to consolidate",
            "prefer quantized classes when practical, otherwise stream a typed style AttrValue",
        );
    }
}

#[derive(Clone, Copy)]
enum SpanOrigin<'a> {
    Macro(&'a MacroInvocation),
    File,
}

impl SpanOrigin<'_> {
    fn line_column(self, span: proc_macro2::Span) -> crate::source::LineColumn {
        match self {
            Self::Macro(inv) => {
                file_line_column_for_body_span(inv, span).unwrap_or(crate::source::LineColumn {
                    line: inv.name_line,
                    column: inv.name_column,
                })
            }
            Self::File => {
                let pos = span.start();
                crate::source::LineColumn {
                    line: pos.line,
                    column: pos.column,
                }
            }
        }
    }
}

fn check_expr_perf(
    path: &Path,
    origin: SpanOrigin<'_>,
    expr: &Expr,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    let mut visitor = PerfVisitor {
        path,
        origin,
        suppressions,
        diagnostics,
        string_builders: HashSet::new(),
        format_locals: HashSet::new(),
        static_markup_locals: HashSet::new(),
        handled_spans: HashSet::new(),
        html: true,
    };
    visitor.visit_expr(expr);
}

struct RsjsVisitor<'a> {
    path: &'a Path,
    suppressions: &'a SuppressionComments,
    diagnostics: &'a mut Vec<Diagnostic>,
    signals: HashSet<String>,
    handlers: HashSet<String>,
    client_locals: HashSet<String>,
    derived_client_locals: HashSet<String>,
    unsupported_client_aliases: HashMap<String, String>,
    /// Locals bound to `rsjs::shared::<T>()`, and the field locals read off
    /// them. Arithmetic touching one of these is resolved at run time rather
    /// than at compile time; see `rsjs/shared-width-dynamic`.
    shared_state_locals: HashSet<String>,
    shared_field_locals: HashSet<String>,
}

impl RsjsVisitor<'_> {
    /// Name of a shared-state field local read in this expression, if any.
    fn shared_field_operand(&self, expr: &Expr) -> Option<String> {
        match expr {
            Expr::Path(path) => {
                let name = path.path.get_ident()?.to_string();
                self.shared_field_locals.contains(&name).then_some(name)
            }
            Expr::MethodCall(call) => self.shared_field_operand(&call.receiver),
            Expr::Paren(paren) => self.shared_field_operand(&paren.expr),
            Expr::Group(group) => self.shared_field_operand(&group.expr),
            Expr::Binary(binary) => self
                .shared_field_operand(&binary.left)
                .or_else(|| self.shared_field_operand(&binary.right)),
            Expr::Unary(unary) => self.shared_field_operand(&unary.expr),
            _ => None,
        }
    }
}

impl<'ast> Visit<'ast> for RsjsVisitor<'_> {
    fn visit_expr_binary(&mut self, node: &'ast syn::ExprBinary) {
        let numeric = matches!(
            node.op,
            syn::BinOp::Add(_)
                | syn::BinOp::Sub(_)
                | syn::BinOp::Mul(_)
                | syn::BinOp::Div(_)
                | syn::BinOp::Rem(_)
                | syn::BinOp::Eq(_)
                | syn::BinOp::Ne(_)
        );
        if numeric {
            if let Some(field) = self
                .shared_field_operand(&node.left)
                .or_else(|| self.shared_field_operand(&node.right))
            {
                push_expr_diag_with_severity(
                    self.path,
                    SpanOrigin::File,
                    self.diagnostics,
                    self.suppressions,
                    node.span(),
                    Severity::Info,
                    "rsjs/shared-width-dynamic",
                    &format!(
                        "`{field}` is a page-shared field, so this operator is resolved at run time, not at compile time"
                    ),
                    "rsjs cannot see a shared field's Rust type, so it emits a representation-dispatching helper (num_add, num_eq, ...) instead of a bare JS operator; mixing a shared field with a fractional Number therefore fails in the browser rather than at build time",
                );
            }
        }
        visit::visit_expr_binary(self, node);
    }

    fn visit_local(&mut self, node: &'ast Local) {
        if let Pat::Ident(pat_ident) = &node.pat {
            if let Some(init) = &node.init {
                let name = pat_ident.ident.to_string();
                // `let count = cart.count();` where `cart` came from
                // `rsjs::shared::<T>()` binds a shared field cell.
                if let Expr::MethodCall(call) = strip_expr_wrappers(&init.expr) {
                    if call.args.is_empty() {
                        if let Expr::Path(receiver) = strip_expr_wrappers(&call.receiver) {
                            if receiver.path.get_ident().is_some_and(|ident| {
                                self.shared_state_locals.contains(&ident.to_string())
                            }) {
                                self.shared_field_locals.insert(name.clone());
                            }
                        }
                    }
                }
                if let Some(kind) = rsjs_named_client_local_kind(&init.expr) {
                    if kind == RsjsNamedClientLocalKind::Signal {
                        self.signals.insert(name.clone());
                    }
                    if kind == RsjsNamedClientLocalKind::SharedState {
                        self.shared_state_locals.insert(name.clone());
                    }
                    if matches!(
                        kind,
                        RsjsNamedClientLocalKind::Handler | RsjsNamedClientLocalKind::EventHandler
                    ) {
                        self.handlers.insert(name.clone());
                    }
                    self.client_locals.insert(name);
                } else if let Some((_span, dependency_name)) = first_reactive_macro_capture(
                    &init.expr,
                    &self.signals,
                    &self.handlers,
                    &self.client_locals,
                    &self.derived_client_locals,
                ) {
                    self.unsupported_client_aliases
                        .insert(name.clone(), dependency_name);
                    self.derived_client_locals.insert(name);
                } else if first_reactive_capture(
                    &init.expr,
                    &self.signals,
                    &self.handlers,
                    &self.client_locals,
                    &self.derived_client_locals,
                )
                .is_some()
                {
                    self.derived_client_locals.insert(name);
                }
            }
        }

        visit::visit_local(self, node);
    }

    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if call_path_is_raw_browser_global(node) {
            push_expr_diag(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "rsjs/window-unchecked",
                "raw browser globals in RSJS code bypass the supported helper surface",
                "use a compiler-known rsjs::window, rsjs::document, or rsjs::location helper; if the capability is missing, add an explicit versioned RSJS browser helper because origin-free #[rsjs::client] functions cannot hide arbitrary DOM access",
            );
        }

        if call_path_is_effect_leak(node) {
            push_expr_diag(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "rsjs/effect-leak",
                "long-lived browser effects need explicit cleanup in RSJS client code",
                "return or register cleanup for timers, observers, and event listeners",
            );
        }

        if call_path_is_nonstatic_selector(node)
            && node
                .args
                .first()
                .is_some_and(|arg| !expr_is_static_string(arg))
        {
            push_expr_diag(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "rsjs/nonstatic-selector",
                "dynamic DOM selectors in RSJS code are brittle and hard to optimize",
                "use a static selector, a node ref, or a data attribute keyed by a static name",
            );
        }

        if call_path_is_json_parse(node) && node.args.iter().any(expr_contains_browser_storage_read)
        {
            push_expr_diag(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "rsjs/localstorage-json",
                "manual JSON parsing from browser storage should use RSJS typed storage helpers",
                "prefer rsjs::local_storage::get_bool_or/get_i64_or/get_f64_or or validate storage input explicitly",
            );
        }

        if let Some(boundary) = rsjs_opaque_boundary_kind(node) {
            for arg in &node.args {
                if let Some((span, name)) = first_reactive_capture(
                    arg,
                    &self.signals,
                    &self.handlers,
                    &self.client_locals,
                    &self.derived_client_locals,
                ) {
                    push_rsjs_unsupported_boundary_capture(
                        self.path,
                        self.diagnostics,
                        self.suppressions,
                        span,
                        boundary,
                        &name,
                    );
                    break;
                }
            }
        }

        visit::visit_expr_call(self, node);
    }

    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        if node.method == "clone"
            && expr_path_single_ident(&node.receiver)
                .is_some_and(|ident| self.signals.contains(&ident))
        {
            push_expr_diag(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "rsjs/signal-clone",
                "cloning an RSJS signal in render/client code is usually unnecessary",
                "pass the signal handle directly to handlers and helpers",
            );
        }

        if method_name_is_effect_leak(&node.method.to_string()) {
            push_expr_diag(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "rsjs/effect-leak",
                "long-lived browser effects need explicit cleanup in RSJS client code",
                "return or register cleanup for timers, observers, and event listeners",
            );
        }

        if method_name_is_nonstatic_selector(&node.method.to_string())
            && node
                .args
                .first()
                .is_some_and(|arg| !expr_is_static_string(arg))
        {
            push_expr_diag(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "rsjs/nonstatic-selector",
                "dynamic DOM selectors in RSJS code are brittle and hard to optimize",
                "use a static selector, a node ref, or a data attribute keyed by a static name",
            );
        }

        visit::visit_expr_method_call(self, node);
    }

    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        let Some(dialect) = template_macro_dialect(node) else {
            visit::visit_expr_macro(self, node);
            return;
        };
        let root = parse_markup_tokens(dialect, node.mac.tokens.clone());
        if let Ok(root) = root {
            for node in &root.nodes {
                self.check_rsjs_template_node(node);
            }
        }
        visit::visit_expr_macro(self, node);
    }
}

impl RsjsVisitor<'_> {
    fn check_rsjs_template_node(&mut self, node: &Node) {
        match node {
            Node::Element(el) => {
                for attr in &el.attrs {
                    if let Attribute::Dynamic { name, value } = attr {
                        self.check_rsjs_template_attr(name, value);
                    }
                }
                for child in &el.children {
                    self.check_rsjs_template_node(child);
                }
            }
            Node::Fragment(children) => {
                for child in children {
                    self.check_rsjs_template_node(child);
                }
            }
            Node::Block(expr) => self.check_rsjs_slot_expr(expr, false, true),
            Node::Text(_) | Node::Doctype(_) => {}
        }
    }

    fn check_rsjs_template_attr(&mut self, name: &MarkupName, value: &Expr) {
        let raw = name.as_markup_str();
        if rsjs_event_attr_name(raw) {
            if !expr_is_rsjs_event_handler_shape(value) {
                push_expr_diag_with_severity(
                    self.path,
                    SpanOrigin::File,
                    self.diagnostics,
                    self.suppressions,
                    value.span(),
                    Severity::Error,
                    "slot/invalid-expression",
                    "RSJS event-handler attributes require a closure or handler ref call",
                    "use `on_click={|_| ...}` or `on_click={handler(payload)}`",
                );
                return;
            }
            self.check_rsjs_slot_expr(value, true, false);
            return;
        }

        if rsjs_bind_attr_name(raw) && !expr_is_bind_signal_shape(value) {
            push_expr_diag_with_severity(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                value.span(),
                Severity::Error,
                "slot/invalid-expression",
                "RSJS bind_* attributes require a signal handle",
                "pass a signal local directly, for example `bind_value={name}`",
            );
            return;
        }

        self.check_rsjs_slot_expr(value, false, false);
    }

    fn check_rsjs_slot_expr(
        &mut self,
        expr: &Expr,
        allow_event_closure: bool,
        allow_template_loop: bool,
    ) {
        if let Expr::Call(call) = expr {
            if let Some(boundary) = rsjs_opaque_boundary_kind(call) {
                for arg in &call.args {
                    if let Some((span, name)) = first_reactive_capture(
                        arg,
                        &self.signals,
                        &self.handlers,
                        &self.client_locals,
                        &self.derived_client_locals,
                    ) {
                        push_rsjs_unsupported_boundary_capture(
                            self.path,
                            self.diagnostics,
                            self.suppressions,
                            span,
                            boundary,
                            &name,
                        );
                        return;
                    }
                }
                if call_path_is_rsjs_server_boundary(call)
                    && call.args.first().is_some_and(|arg| {
                        expr_is_simple_ssr_value(arg) && !expr_is_rooted_at_self(arg)
                    })
                {
                    push_expr_diag(
                        self.path,
                        SpanOrigin::File,
                        self.diagnostics,
                        self.suppressions,
                        call.span(),
                        "rsjs/unnecessary-server-only",
                        "opaque RSJS server boundary wraps a simple SSR value",
                        "remove the wrapper; simple literals, ordinary locals, and their field projections render on the server in v2",
                    );
                }
                return;
            }
        }
        if let Some((span, local_name, dependency_name)) =
            first_unsupported_client_alias_capture(expr, &self.unsupported_client_aliases)
        {
            push_rsjs_unsupported_client_alias(
                self.path,
                self.diagnostics,
                self.suppressions,
                span,
                &local_name,
                &dependency_name,
            );
            return;
        }
        if let Some(problem) =
            unsupported_rsjs_slot_expr(expr, allow_event_closure, allow_template_loop)
        {
            push_expr_diag_with_severity(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                problem.span,
                Severity::Error,
                "slot/invalid-expression",
                problem.message,
                problem.help,
            );
            return;
        }
        if let Some(problem) = unrecognised_rsjs_slot_helper_call(expr, allow_template_loop) {
            push_expr_diag_with_severity(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                problem.span,
                Severity::Error,
                "slot/invalid-expression",
                &problem.message,
                problem.help.as_str(),
            );
        }
    }
}

struct AttrValueVisitor<'a> {
    path: &'a Path,
    suppressions: &'a SuppressionComments,
    diagnostics: &'a mut Vec<Diagnostic>,
    stream_ops: usize,
    has_control_flow: bool,
    has_text_macro: bool,
}

impl<'ast> Visit<'ast> for AttrValueVisitor<'_> {
    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if attr_value_raw_segment_in_call(node) {
            push_expr_diag(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/raw-attr-segment",
                "raw attribute byte segments bypass Proa attribute escaping",
                "use `text!(...)` or render the dynamic segment through `AttrValue::render_attr_value`",
            );
        }
        if call_is_attr_stream_op(node) {
            self.stream_ops += 1;
        }

        visit::visit_expr_call(self, node);
    }

    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        if attr_value_raw_segment_in_method_call(node) {
            push_expr_diag(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/raw-attr-segment",
                "raw attribute byte segments bypass Proa attribute escaping",
                "use `text!(...)` or render the dynamic segment through `AttrValue::render_attr_value`",
            );
        }
        if method_is_attr_stream_op(node) {
            self.stream_ops += 1;
        }

        visit::visit_expr_method_call(self, node);
    }

    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        if macro_path_ends(node, "text") {
            self.has_text_macro = true;
        }

        visit::visit_expr_macro(self, node);
    }

    fn visit_expr_for_loop(&mut self, node: &'ast syn::ExprForLoop) {
        self.has_control_flow = true;
        visit::visit_expr_for_loop(self, node);
    }

    fn visit_expr_if(&mut self, node: &'ast syn::ExprIf) {
        self.has_control_flow = true;
        visit::visit_expr_if(self, node);
    }

    fn visit_expr_loop(&mut self, node: &'ast syn::ExprLoop) {
        self.has_control_flow = true;
        visit::visit_expr_loop(self, node);
    }

    fn visit_expr_match(&mut self, node: &'ast syn::ExprMatch) {
        self.has_control_flow = true;
        visit::visit_expr_match(self, node);
    }

    fn visit_expr_while(&mut self, node: &'ast syn::ExprWhile) {
        self.has_control_flow = true;
        visit::visit_expr_while(self, node);
    }
}

struct PerfVisitor<'a> {
    html: bool,
    path: &'a Path,
    origin: SpanOrigin<'a>,
    suppressions: &'a SuppressionComments,
    diagnostics: &'a mut Vec<Diagnostic>,
    string_builders: HashSet<String>,
    format_locals: HashSet<String>,
    static_markup_locals: HashSet<String>,
    /// Call spans already reported through a more specific rule (for
    /// example `return String::new()` sentinels), keyed by (line, column).
    handled_spans: HashSet<(usize, usize)>,
}

impl<'ast> Visit<'ast> for PerfVisitor<'_> {
    fn visit_expr_return(&mut self, node: &'ast syn::ExprReturn) {
        // `return String::new()` / `return Vec::new()` sentinels are usually
        // deliberate empty-result fast paths, not per-render allocation
        // churn: report them as info instead of warning.
        if let Some(expr) = &node.expr {
            if let Expr::Call(call) = expr.as_ref() {
                if call_path_ends(call, &["String", "new"]) || call_path_ends(call, &["Vec", "new"])
                {
                    let span = call.span();
                    self.handled_spans
                        .insert((span.start().line, span.start().column));
                    push_expr_diag_with_severity(
                        self.path,
                        self.origin,
                        self.diagnostics,
                        self.suppressions,
                        span,
                        Severity::Info,
                        "perf/empty-sentinel-return",
                        "empty-buffer sentinel returned from a render-path function",
                        "fine for cold early-returns; annotate `// proa-perf-ok: reason` to silence, or return a borrowed empty value",
                    );
                }
            }
        }
        visit::visit_expr_return(self, node);
    }

    fn visit_local(&mut self, node: &'ast Local) {
        if let Pat::Ident(pat_ident) = &node.pat {
            if let Some(init) = &node.init {
                if expr_is_string_builder_init(&init.expr) {
                    self.string_builders.insert(pat_ident.ident.to_string());
                } else if expr_is_format_macro(&init.expr) {
                    self.format_locals.insert(pat_ident.ident.to_string());
                } else if expr_string_literal(&init.expr)
                    .is_some_and(|lit| string_looks_like_html(&lit.value()))
                {
                    self.static_markup_locals
                        .insert(pat_ident.ident.to_string());
                }
            }
        }

        visit::visit_local(self, node);
    }

    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if is_perf_suppressed_call(node) {
            return;
        }

        if matches!(self.origin, SpanOrigin::Macro(inv) if inv.dialect == MacroDialect::Html)
            && call_is_staticraw_doctype(node)
        {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "html/staticraw-doctype",
                "StaticRaw(\"<!DOCTYPE html>\") hides the document doctype from the HTML macro",
                "write `<!DOCTYPE html>` directly in the html!/html_sync! macro; Proa will emit the doctype and its render marker",
            );
        }

        if call_path_ends(node, &["String", "from"])
            && node.args.first().is_some_and(expr_is_static_string)
        {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "render/static-string-to-string",
                "static string literal is converted to an owned String in a render path",
                "use `&'static str`, an enum label method, or render the literal directly",
            );
        } else if call_path_ends(node, &["String", "from"]) {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/string-from",
                "String::from() in a Proa render path allocates on every render",
                "use the borrowed string directly when possible",
            );
        }
        if call_path_ends(node, &["String", "new"])
            && !self
                .handled_spans
                .contains(&(node.span().start().line, node.span().start().column))
        {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/string-new",
                "String::new() in a Proa render path allocates on every render",
                "use a borrowed value, a static string, or precompute outside render",
            );
        }
        if call_path_ends(node, &["String", "with_capacity"]) {
            push_expr_diag_with_severity(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                Severity::Info,
                "perf/string-with-capacity",
                "String::with_capacity() in a Proa render path allocates on every render",
                "pre-sizing plus `write!` is the preferred shape when assembly is unavoidable; hoist or pool the buffer if this path is hot",
            );
        }
        if call_path_ends(node, &["Vec", "new"])
            && !self
                .handled_spans
                .contains(&(node.span().start().line, node.span().start().column))
        {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/vec-new",
                "Vec::new() in a Proa render path allocates on every render",
                "use a fixed array/slice or render items directly",
            );
        }
        if call_path_ends(node, &["Vec", "with_capacity"]) {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/vec-with-capacity",
                "Vec::with_capacity() in a Proa render path allocates on every render",
                "render items directly or use stack storage",
            );
        }
        if call_path_ends(node, &["serde_json", "to_string"])
            || call_path_ends(node, &["serde_json", "to_string_pretty"])
        {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/serde-json-to-string",
                "serde_json::to_string() in a Proa render path allocates on every render",
                "precompute serialized data before render or write a dedicated renderable wrapper",
            );
        }
        if call_path_ends(node, &["render_to_string"]) {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/render-to-string",
                "render_to_string() in a Proa render path allocates an intermediate String",
                "render the child directly into the existing WebContext",
            );
        }
        if call_path_ends(node, &["UnsafeRaw"]) {
            let help = if node.args.first().is_some_and(expr_looks_static_str) {
                "the argument looks 'static: use StaticRaw(...) so consolidation and the escape audit are preserved"
            } else {
                "for pre-rendered fragments restructure as a single-pass component slot (see perf/render-copy); for static assets use StaticRaw; otherwise wrap only the dynamic segment in a typed component or AttrValue"
            };
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/unsafe-raw-string",
                "UnsafeRaw in a Proa render path bypasses template escaping and consolidation",
                help,
            );
        }
        if self.html && call_path_is_manual_escape(node) {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/manual-escape",
                "manual escaping in a Proa render path usually allocates or bypasses template checks",
                "let html_sync! escape text and attributes, or implement a focused AttrValue wrapper",
            );
        }
        if self.html && call_path_is_raw_write(node) && node.args.iter().any(expr_is_html_literal) {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/raw-write-html",
                "raw WriteBuf HTML writes bypass template consolidation and escaping checks",
                "use html_sync! for markup and keep raw writes to narrow low-level helpers",
            );
        }

        visit::visit_expr_call(self, node);
    }

    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        if let Some(seg) = node.mac.path.segments.last() {
            match seg.ident.to_string().as_str() {
                "format" => push_expr_diag(
                    self.path,
                    self.origin,
                    self.diagnostics,
                    self.suppressions,
                    node.span(),
                    "perf/format",
                    "format!() in a Proa render path allocates a String on every render",
                    "for text, render adjacent pieces like `\"$\"{price}\" / night\"`; for attrs, precompute or use `text!(...)`",
                ),
                "vec" => push_expr_diag(
                    self.path,
                    self.origin,
                    self.diagnostics,
                    self.suppressions,
                    node.span(),
                    "perf/vec",
                    "vec![] in a Proa render path allocates a Vec on every render",
                    "use a const array or borrowed slice when possible",
                ),
                _ => {}
            }
        }

        self.check_template_static_markup_raw(node);
        self.check_template_attr_builder_perf(node);
        if template_macro_dialect(node).is_none() {
            self.check_macro_arg_exprs(node);
        }
        visit::visit_expr_macro(self, node);
    }

    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        match node.method.to_string().as_str() {
            "to_string" if expr_is_static_string(&node.receiver) => push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "render/static-string-to-string",
                "static string literal is converted to an owned String in a render path",
                "use `&'static str`, an enum label method, or render the literal directly",
            ),
            "to_string" => push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/to-string",
                ".to_string() in a Proa render path allocates on every render",
                "pass the value directly when it implements Proa rendering",
            ),
            "to_owned" if expr_is_static_string(&node.receiver) => push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "render/static-string-to-string",
                "static string literal is converted to an owned String in a render path",
                "use `&'static str`, an enum label method, or render the literal directly",
            ),
            "to_owned" => push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/to-owned",
                ".to_owned() in a Proa render path allocates or clones on every render",
                "borrow the value directly when possible",
            ),
            "join" => push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/join",
                ".join() in a Proa render path allocates a String on every render",
                "render items in a loop instead of joining into an intermediate String",
            ),
            "collect" => push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/collect",
                ".collect() in a Proa render path allocates a collection on every render",
                "iterate the original iterator directly when possible",
            ),
            "push_str" => push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/push-str",
                ".push_str() in a Proa render path usually means a String is being assembled; prefer `write!` into one pre-sized buffer or a component slot",
                "write directly through html_sync! or use an AttrValue/renderable wrapper",
            ),
            "push" => push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/string-push",
                ".push() in a Proa render path usually means a String or Vec is being assembled",
                "write directly through html_sync! or use stack storage",
            ),
            "clone" if !expr_looks_like_large_render_data(&node.receiver) => push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/clone",
                ".clone() in a Proa render path may allocate or bump refcounts",
                "prefer borrowing or moving once outside the render path; wrap in `perf_ok(...)` if intentional",
            ),
            _ => {}
        }

        if node.method == "render_to_string" {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/render-to-string",
                "render_to_string() in a Proa render path allocates an intermediate String",
                "render the child directly into the existing WebContext",
            );
        }
        if self.html
            && matches!(node.method.to_string().as_str(), "extend" | "extend_static")
            && node.args.iter().any(expr_is_html_literal)
        {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/raw-write-html",
                "raw HTML writes bypass template consolidation and escaping checks",
                "use html_sync! for markup and keep raw writes to narrow low-level helpers",
            );
        }
        if node.method == "push_str" && node.args.iter().any(expr_contains_format_macro) {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/format-push-str-loop",
                "push_str(format!(...)) allocates an intermediate String in the render path",
                "stream pieces with html_sync!, text!, AttrValue, or direct render wrappers",
            );
        }
        if node.method == "push_str"
            && expr_path_single_ident(&node.receiver)
                .is_some_and(|ident| self.string_builders.contains(&ident))
            && node.args.iter().any(expr_is_html_literal)
        {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/raw-html-buffer",
                "String buffer assembly with HTML fragments bypasses template consolidation",
                "render a small component with html_sync! instead of building an HTML string",
            );
        }

        visit::visit_expr_method_call(self, node);
    }

    fn visit_expr_binary(&mut self, node: &'ast ExprBinary) {
        if matches!(node.op, BinOp::Add(_)) && binary_mentions_string_literal(node) {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                node.span(),
                "perf/string-add",
                "string concatenation inside a Proa macro may allocate in the render path",
                "render adjacent text/value segments directly instead of building an intermediate String",
            );
        }

        visit::visit_expr_binary(self, node);
    }
}

impl PerfVisitor<'_> {
    fn check_template_static_markup_raw(&mut self, node: &ExprMacro) {
        if self.static_markup_locals.is_empty() || template_macro_dialect(node).is_none() {
            return;
        }
        self.check_template_static_markup_raw_tokens(node.mac.tokens.clone());
    }

    fn check_template_static_markup_raw_tokens(&mut self, tokens: proc_macro2::TokenStream) {
        let tokens: Vec<_> = tokens.into_iter().collect();
        for (idx, token) in tokens.iter().enumerate() {
            match token {
                proc_macro2::TokenTree::Ident(ident) if ident == "UnsafeRaw" => {
                    let Some(proc_macro2::TokenTree::Group(args)) = tokens.get(idx + 1) else {
                        continue;
                    };
                    if args.delimiter() != proc_macro2::Delimiter::Parenthesis {
                        continue;
                    }
                    let Ok(arg) = syn::parse2::<Expr>(args.stream()) else {
                        continue;
                    };
                    if !expr_is_local_static_markup(&arg, &self.static_markup_locals) {
                        continue;
                    }
                    push_expr_diag(
                        self.path,
                        self.origin,
                        self.diagnostics,
                        self.suppressions,
                        ident.span(),
                        "perf/static-markup-raw-local",
                        "static SVG/HTML stored in a local string is passed through UnsafeRaw",
                        "render the markup with html_sync! or a small component; if raw passthrough is intentional, use StaticRaw on a const",
                    );
                }
                proc_macro2::TokenTree::Group(group) => {
                    self.check_template_static_markup_raw_tokens(group.stream());
                }
                _ => {}
            }
        }
    }

    fn check_template_attr_builder_perf(&mut self, node: &ExprMacro) {
        let Some(dialect) = template_macro_dialect(node) else {
            return;
        };
        let root = parse_markup_tokens(dialect, node.mac.tokens.clone());
        let Ok(root) = root else {
            return;
        };
        for node in &root.nodes {
            self.check_template_attr_builder_node(node);
        }
    }

    fn check_template_attr_builder_node(&mut self, node: &Node) {
        match node {
            Node::Element(el) => {
                for attr in &el.attrs {
                    self.check_template_attr_builder_attr(attr);
                }
                for child in &el.children {
                    self.check_template_attr_builder_node(child);
                }
            }
            Node::Fragment(children) => {
                for child in children {
                    self.check_template_attr_builder_node(child);
                }
            }
            Node::Text(_) | Node::Block(_) | Node::Doctype(_) => {}
        }
    }

    fn check_template_attr_builder_attr(&mut self, attr: &Attribute) {
        let Attribute::Dynamic { name, value } = attr else {
            return;
        };
        let Some(ident) = expr_path_single_ident(value) else {
            return;
        };
        if self.string_builders.contains(&ident) && attr_accepts_streamed_value(name) {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                value.span(),
                "perf/attr-string-builder",
                "String is built only to be used as a dynamic attribute value",
                "use a typed AttrValue or text!(...) so Proa can stream the attribute without allocation",
            );
        }
        if self.format_locals.contains(&ident) && attr_is_preformatted_label(name) {
            push_expr_diag(
                self.path,
                self.origin,
                self.diagnostics,
                self.suppressions,
                value.span(),
                "perf/preformatted-aria",
                "formatted label strings used only as attributes allocate in the render path",
                "use text!(...) or a small AttrValue wrapper for aria/title labels",
            );
        }
    }

    fn check_macro_arg_exprs(&mut self, node: &ExprMacro) {
        let parser = Punctuated::<Expr, Token![,]>::parse_terminated;
        if let Ok(args) = parser.parse2(node.mac.tokens.clone()) {
            for arg in args {
                self.visit_expr(&arg);
            }
        }
    }
}

#[allow(clippy::too_many_arguments)]
/// Heuristic: does this expression look like a `&'static str` (string
/// literal, `include_str!`, or a SCREAMING_SNAKE/const-like path)?
fn expr_looks_static_str(expr: &Expr) -> bool {
    let mut inner = expr;
    while let Expr::Reference(reference) = inner {
        inner = reference.expr.as_ref();
    }
    match inner {
        Expr::Lit(lit) => matches!(lit.lit, Lit::Str(_)),
        Expr::Macro(mac) => mac
            .mac
            .path
            .segments
            .last()
            .is_some_and(|seg| seg.ident == "include_str"),
        Expr::Path(expr_path) => expr_path.path.segments.last().is_some_and(|seg| {
            let name = seg.ident.to_string();
            !name.is_empty() && name.chars().all(|c| c.is_ascii_uppercase() || c == '_')
        }),
        Expr::Call(call) => call_last_segment(call)
            .is_some_and(|seg| seg.ends_with("_style") || seg.ends_with("_css")),
        _ => false,
    }
}

fn call_is_staticraw_doctype(call: &ExprCall) -> bool {
    call_path_ends(call, &["StaticRaw"])
        && call.args.first().is_some_and(|arg| {
            expr_string_literal(arg)
                .is_some_and(|lit| lit.value().trim().eq_ignore_ascii_case("<!DOCTYPE html>"))
        })
}

fn expr_is_local_static_markup(expr: &Expr, locals: &HashSet<String>) -> bool {
    let mut inner = expr;
    loop {
        match inner {
            Expr::Reference(reference) => inner = reference.expr.as_ref(),
            Expr::Group(group) => inner = &group.expr,
            Expr::Paren(paren) => inner = &paren.expr,
            _ => break,
        }
    }
    expr_path_single_ident(inner).is_some_and(|ident| locals.contains(&ident))
}

#[allow(clippy::too_many_arguments)]
fn push_expr_diag(
    path: &Path,
    origin: SpanOrigin<'_>,
    diagnostics: &mut Vec<Diagnostic>,
    suppressions: &SuppressionComments,
    span: proc_macro2::Span,
    code: &'static str,
    message: &str,
    help: &str,
) {
    push_expr_diag_with_severity(
        path,
        origin,
        diagnostics,
        suppressions,
        span,
        Severity::Warning,
        code,
        message,
        help,
    );
}

#[allow(clippy::too_many_arguments)]
fn push_expr_diag_with_severity(
    path: &Path,
    origin: SpanOrigin<'_>,
    diagnostics: &mut Vec<Diagnostic>,
    suppressions: &SuppressionComments,
    span: proc_macro2::Span,
    severity: Severity,
    code: &'static str,
    message: &str,
    help: &str,
) {
    let pos = origin.line_column(span);
    if pos.line == 0 {
        return;
    }
    if suppressions.is_suppressed(pos.line, code) {
        return;
    }
    diagnostics.push(
        Diagnostic::new(path, pos.line, pos.column + 1, severity, code, message).with_help(help),
    );
}

#[allow(clippy::too_many_arguments)]
fn push_source_diag_with_severity(
    path: &Path,
    diagnostics: &mut Vec<Diagnostic>,
    suppressions: &SuppressionComments,
    line: usize,
    column: usize,
    severity: Severity,
    code: &'static str,
    message: &str,
    help: &str,
) {
    if line == 0 || suppressions.is_suppressed(line, code) {
        return;
    }
    diagnostics.push(Diagnostic::new(path, line, column, severity, code, message).with_help(help));
}

fn push_rsjs_unsupported_boundary_capture(
    path: &Path,
    diagnostics: &mut Vec<Diagnostic>,
    suppressions: &SuppressionComments,
    span: proc_macro2::Span,
    boundary: RsjsOpaqueBoundaryKind,
    name: &str,
) {
    let (message, help) = match boundary {
        RsjsOpaqueBoundaryKind::ServerOnly | RsjsOpaqueBoundaryKind::ServerAttr => (
            format!("opaque RSJS server boundary captures client-side `{name}`"),
            "move the value out of rsjs::server_only/server_attr, pass plain server data, or render reactive/browser work directly",
        ),
        RsjsOpaqueBoundaryKind::Island => (
            format!("explicit RSJS island boundary captures parent client-side `{name}`"),
            "move the value out of rsjs::island(...), render the child directly for parent reactive state, or pass plain server data into an independent child island",
        ),
    };
    push_expr_diag_with_severity(
        path,
        SpanOrigin::File,
        diagnostics,
        suppressions,
        span,
        Severity::Error,
        "rsjs/unsupported-capture",
        &message,
        help,
    );
}

fn push_rsjs_unsupported_client_alias(
    path: &Path,
    diagnostics: &mut Vec<Diagnostic>,
    suppressions: &SuppressionComments,
    span: proc_macro2::Span,
    local_name: &str,
    dependency_name: &str,
) {
    push_expr_diag_with_severity(
        path,
        SpanOrigin::File,
        diagnostics,
        suppressions,
        span,
        Severity::Error,
        "rsjs/unsupported-client-alias",
        &format!(
            "prelude local `{local_name}` depends on client-side `{dependency_name}` through unsupported Rust syntax"
        ),
        "move this logic into a standalone helper annotated once with #[rsjs::client], render the supported client expression directly, or compute a plain server value before touching rsjs client primitives",
    );
}

