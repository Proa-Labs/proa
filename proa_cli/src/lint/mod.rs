struct UnrecognisedRsjsSlotHelperCall {
    span: proc_macro2::Span,
    message: String,
    help: String,
}

fn unrecognised_rsjs_slot_helper_call(
    expr: &Expr,
    allow_template_loop: bool,
) -> Option<UnrecognisedRsjsSlotHelperCall> {
    let mut visitor = UnrecognisedRsjsSlotHelperCallVisitor {
        allow_template_loop,
        problem: None,
    };
    visitor.visit_expr(expr);
    visitor.problem
}

struct UnrecognisedRsjsSlotHelperCallVisitor {
    allow_template_loop: bool,
    problem: Option<UnrecognisedRsjsSlotHelperCall>,
}

impl UnrecognisedRsjsSlotHelperCallVisitor {
    fn push_server_owned_self(&mut self, span: proc_macro2::Span) {
        if self.problem.is_some() {
            return;
        }
        self.problem = Some(UnrecognisedRsjsSlotHelperCall {
            span,
            message: "`self` data is server-owned and cannot be read directly by client-reactive IR"
                .to_string(),
            help: "seed the value before the template with `let value = signal(self.field);` and pass `value.get()` to the client helper, or precompute server-only output before the template / wrap opaque SSR in `rsjs::server_only(...)`"
                .to_string(),
        });
    }
}

impl<'ast> Visit<'ast> for UnrecognisedRsjsSlotHelperCallVisitor {
    fn visit_expr_for_loop(&mut self, node: &'ast syn::ExprForLoop) {
        if self.allow_template_loop && for_loop_has_template_body(node) {
            return;
        }
        visit::visit_expr_for_loop(self, node);
    }

    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if self.problem.is_some() {
            return;
        }
        if call_path_is_rsjs_opaque_boundary(node) {
            return;
        }
        if call_path_is_rsjs_client_primitive(node) || call_path_is_rsjs_browser_helper(node) {
            visit::visit_expr_call(self, node);
            return;
        }
        let Expr::Path(_) = node.func.as_ref() else {
            visit::visit_expr_call(self, node);
            return;
        };
        // Source lint cannot soundly resolve whether an ordinary Rust path
        // reaches a `#[rsjs::client]` definition, especially through imports,
        // aliases, and re-exports. Accept every statically spelled candidate
        // here and let the relocation-backed semantic linker prove the exact
        // definition. Keep source-local argument checks that do not require
        // name resolution.
        if let Some(span) = node.args.iter().find_map(first_self_rooted_expr_span) {
            self.push_server_owned_self(span);
            return;
        }
        visit::visit_expr_call(self, node);
    }
}

fn first_self_rooted_expr_span(expr: &Expr) -> Option<proc_macro2::Span> {
    struct Finder {
        span: Option<proc_macro2::Span>,
    }

    impl<'ast> Visit<'ast> for Finder {
        fn visit_expr(&mut self, node: &'ast Expr) {
            if self.span.is_some() {
                return;
            }
            if expr_is_rooted_at_self(node) {
                self.span = Some(node.span());
                return;
            }
            visit::visit_expr(self, node);
        }
    }

    let mut finder = Finder { span: None };
    finder.visit_expr(expr);
    finder.span
}

fn expr_is_rooted_at_self(expr: &Expr) -> bool {
    match expr {
        Expr::Path(path) => path.path.is_ident("self"),
        Expr::Field(field) => expr_is_rooted_at_self(&field.base),
        Expr::Index(index) => expr_is_rooted_at_self(&index.expr),
        Expr::MethodCall(method) => expr_is_rooted_at_self(&method.receiver),
        Expr::Paren(paren) => expr_is_rooted_at_self(&paren.expr),
        Expr::Group(group) => expr_is_rooted_at_self(&group.expr),
        Expr::Reference(reference) => expr_is_rooted_at_self(&reference.expr),
        _ => false,
    }
}

fn unsupported_rsjs_slot_expr(
    expr: &Expr,
    allow_event_closure: bool,
    allow_template_loop: bool,
) -> Option<UnsupportedRsjsSlotExpr> {
    let mut visitor = UnsupportedRsjsSlotExprVisitor {
        allow_event_closure,
        allow_template_loop,
        problem: None,
    };
    visitor.visit_expr(expr);
    visitor.problem
}

struct UnsupportedRsjsSlotExprVisitor {
    allow_event_closure: bool,
    allow_template_loop: bool,
    problem: Option<UnsupportedRsjsSlotExpr>,
}

impl UnsupportedRsjsSlotExprVisitor {
    fn push(&mut self, span: proc_macro2::Span, message: &'static str, help: &'static str) {
        if self.problem.is_none() {
            self.problem = Some(UnsupportedRsjsSlotExpr {
                span,
                message,
                help,
            });
        }
    }
}

impl<'ast> Visit<'ast> for UnsupportedRsjsSlotExprVisitor {
    fn visit_expr_closure(&mut self, node: &'ast syn::ExprClosure) {
        if !self.allow_event_closure {
            self.push(
                node.span(),
                "closures cannot be rendered as client-reactive RSJS slot values",
                "move effects into supported handler operations; move only portable origin-free computation into a standalone #[rsjs::client] helper",
            );
            return;
        }
        if node.inputs.len() > 1 {
            self.push(
                node.span(),
                "RSJS event handlers accept at most one event parameter",
                "use a single event parameter and pass additional data through a handler ref payload",
            );
            return;
        }
        visit::visit_expr_closure(self, node);
    }

    fn visit_expr_match(&mut self, node: &'ast syn::ExprMatch) {
        self.push(
            node.match_token.span,
            "match expressions are outside the current RSJS slot grammar",
            "rewrite as a value if/else, move logic to a standalone #[rsjs::client] helper, or wrap server-only output in rsjs::server_only(...)",
        );
    }

    fn visit_expr_for_loop(&mut self, node: &'ast syn::ExprForLoop) {
        if self.allow_template_loop && for_loop_has_template_body(node) {
            return;
        }
        self.push(
            node.for_token.span,
            "for loops are outside the current RSJS slot grammar",
            "precompute server-only collections, use supported static/range handler loops, or move client logic to a helper",
        );
    }

    fn visit_expr_while(&mut self, node: &'ast syn::ExprWhile) {
        self.push(
            node.while_token.span,
            "while loops are outside the current RSJS slot grammar",
            "move iterative client logic to a standalone #[rsjs::client] helper or keep it server-only",
        );
    }

    fn visit_expr_loop(&mut self, node: &'ast syn::ExprLoop) {
        self.push(
            node.loop_token.span,
            "loop expressions are outside the current RSJS slot grammar",
            "move iterative client logic to a standalone #[rsjs::client] helper or keep it server-only",
        );
    }

    fn visit_expr_async(&mut self, node: &'ast syn::ExprAsync) {
        self.push(
            node.async_token.span,
            "async blocks are outside the current RSJS slot grammar",
            "move asynchronous client work into rsjs query/mutation APIs; #[rsjs::client] helpers are origin-free and synchronous",
        );
    }

    fn visit_expr_unsafe(&mut self, node: &'ast syn::ExprUnsafe) {
        self.push(
            node.unsafe_token.span,
            "unsafe blocks are outside the current RSJS slot grammar",
            "keep unsafe/server-only rendering outside client-reactive slots",
        );
    }

    fn visit_expr_return(&mut self, node: &'ast syn::ExprReturn) {
        self.push(
            node.return_token.span,
            "return expressions are outside the current RSJS slot grammar",
            "make the slot expression evaluate to a supported value instead of returning from render",
        );
    }

    fn visit_expr_break(&mut self, node: &'ast syn::ExprBreak) {
        self.push(
            node.break_token.span,
            "break expressions are outside the current RSJS slot grammar",
            "move control flow into a supported helper or keep it outside the slot",
        );
    }

    fn visit_expr_continue(&mut self, node: &'ast syn::ExprContinue) {
        self.push(
            node.continue_token.span,
            "continue expressions are outside the current RSJS slot grammar",
            "move control flow into a supported helper or keep it outside the slot",
        );
    }
}

fn first_reactive_capture(
    expr: &Expr,
    signals: &HashSet<String>,
    handlers: &HashSet<String>,
    client_locals: &HashSet<String>,
    derived_client_locals: &HashSet<String>,
) -> Option<(proc_macro2::Span, String)> {
    let mut visitor = ReactiveCaptureFinder {
        signals,
        handlers,
        client_locals,
        derived_client_locals,
        capture: None,
    };
    visitor.visit_expr(expr);
    visitor.capture
}

fn first_reactive_macro_capture(
    expr: &Expr,
    signals: &HashSet<String>,
    handlers: &HashSet<String>,
    client_locals: &HashSet<String>,
    derived_client_locals: &HashSet<String>,
) -> Option<(proc_macro2::Span, String)> {
    let mut visitor = ReactiveMacroCaptureFinder {
        signals,
        handlers,
        client_locals,
        derived_client_locals,
        capture: None,
    };
    visitor.visit_expr(expr);
    visitor.capture
}

fn first_unsupported_client_alias_capture(
    expr: &Expr,
    unsupported_client_aliases: &HashMap<String, String>,
) -> Option<(proc_macro2::Span, String, String)> {
    struct Finder<'a> {
        unsupported_client_aliases: &'a HashMap<String, String>,
        capture: Option<(proc_macro2::Span, String, String)>,
    }

    impl<'ast> Visit<'ast> for Finder<'_> {
        fn visit_expr_path(&mut self, node: &'ast ExprPath) {
            if self.capture.is_some() {
                return;
            }
            if let Some(ident) = node.path.get_ident() {
                let name = ident.to_string();
                if let Some(dependency_name) = self.unsupported_client_aliases.get(&name) {
                    self.capture = Some((ident.span(), name, dependency_name.clone()));
                    return;
                }
            }
            visit::visit_expr_path(self, node);
        }
    }

    let mut finder = Finder {
        unsupported_client_aliases,
        capture: None,
    };
    finder.visit_expr(expr);
    finder.capture
}

struct ReactiveCaptureFinder<'a> {
    signals: &'a HashSet<String>,
    handlers: &'a HashSet<String>,
    client_locals: &'a HashSet<String>,
    derived_client_locals: &'a HashSet<String>,
    capture: Option<(proc_macro2::Span, String)>,
}

impl ReactiveCaptureFinder<'_> {
    fn capture(&mut self, span: proc_macro2::Span, name: String) {
        if self.capture.is_none() {
            self.capture = Some((span, name));
        }
    }
}

impl<'ast> Visit<'ast> for ReactiveCaptureFinder<'_> {
    fn visit_expr_path(&mut self, node: &'ast ExprPath) {
        if let Some(ident) = node.path.get_ident() {
            let name = ident.to_string();
            if self.signals.contains(&name)
                || self.handlers.contains(&name)
                || self.client_locals.contains(&name)
                || self.derived_client_locals.contains(&name)
            {
                self.capture(ident.span(), name);
                return;
            }
        }
        visit::visit_expr_path(self, node);
    }

    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if let Some((span, name)) =
            rsjs_client_primitive_capture(node).or_else(|| rsjs_browser_helper_capture(node))
        {
            self.capture(span, name);
            return;
        }
        visit::visit_expr_call(self, node);
    }
}

struct ReactiveMacroCaptureFinder<'a> {
    signals: &'a HashSet<String>,
    handlers: &'a HashSet<String>,
    client_locals: &'a HashSet<String>,
    derived_client_locals: &'a HashSet<String>,
    capture: Option<(proc_macro2::Span, String)>,
}

impl<'ast> Visit<'ast> for ReactiveMacroCaptureFinder<'_> {
    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        if self.capture.is_some() {
            return;
        }
        let parser = syn::punctuated::Punctuated::<Expr, syn::Token![,]>::parse_terminated;
        if let Ok(args) = syn::parse::Parser::parse2(parser, node.mac.tokens.clone()) {
            for arg in args {
                if let Some(capture) = first_reactive_capture(
                    &arg,
                    self.signals,
                    self.handlers,
                    self.client_locals,
                    self.derived_client_locals,
                ) {
                    self.capture = Some(capture);
                    return;
                }
                self.visit_expr(&arg);
                if self.capture.is_some() {
                    return;
                }
            }
        }
    }
}
