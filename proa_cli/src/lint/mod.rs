#[derive(Debug, Clone, Default)]
pub struct LintOptions {
    pub include_tests: bool,
    pub rsjs_strategy_cache: Option<RsjsStrategyCacheOptions>,
    pub content: content::ContentOptions,
}

pub fn lint_file(path: &Path, source: &str) -> Vec<Diagnostic> {
    lint_file_with_options(path, source, LintOptions::default())
}

pub fn lint_file_with_options(path: &Path, source: &str, options: LintOptions) -> Vec<Diagnostic> {
    let rsjs_strategy_cache = options
        .rsjs_strategy_cache
        .as_ref()
        .map(RsjsStrategyCache::load);
    let mut diagnostics = lint_file_with_cache(
        path,
        source,
        options.include_tests,
        rsjs_strategy_cache.as_ref(),
    );
    diagnostics.extend(content::lint_sources(
        &[(path.to_owned(), source.to_owned())],
        &std::collections::BTreeSet::from([content::absolute(path)]),
        options.include_tests,
        &options.content,
    ));
    diagnostics
}

fn lint_file_with_cache(
    path: &Path,
    source: &str,
    include_tests: bool,
    rsjs_strategy_cache: Option<&RsjsStrategyCache>,
) -> Vec<Diagnostic> {
    let display = display_path(path);
    let mut diagnostics = Vec::new();
    if !include_tests && is_test_path(path) {
        return diagnostics;
    }

    let test_ranges = if include_tests {
        Vec::new()
    } else {
        cfg_test_module_line_ranges(source)
    };
    // Generated sources (marked `@generated` or `GENERATED by ...` near the
    // top) keep their perf and correctness lints, but formatting lints are
    // meaningless noise for machine-written layout.
    let is_generated = source
        .lines()
        .take(5)
        .any(|line| line.contains("@generated") || line.contains("GENERATED by"));

    let parsed_file = syn::parse_file(source).ok();
    let mut suppressions = SuppressionComments::new(source);
    if let Some(file) = &parsed_file {
        suppressions.attach_item_scopes(file);
    }
    let suppressions = suppressions;
    suppressions.push_invalid_diagnostics(&display, &test_ranges, &mut diagnostics);

    // Each macro body is located and parsed exactly once; the format
    // canonicalization pass below reuses these results instead of re-scanning
    // the source.
    let rsjs_ranges = crate::fmt::rsjs_line_ranges(source);
    let parsed_macros: Vec<(MacroInvocation, syn::Result<HtmlRoot>)> = find_macros(source)
        .into_iter()
        .map(|inv| {
            let parsed = parse_invocation(source, &inv);
            (inv, parsed)
        })
        .collect();

    for (inv, parsed) in &parsed_macros {
        if line_in_ranges(inv.name_line, &test_ranges) {
            continue;
        }

        match parsed {
            Ok(root) => {
                if !is_generated {
                    lint_indentation(&display, inv, root, &mut diagnostics);
                }
                lint_template_accessibility(&display, inv, root, &suppressions, &mut diagnostics);
                lint_perf(
                    &display,
                    inv,
                    root,
                    line_in_ranges(inv.name_line, &rsjs_ranges),
                    &suppressions,
                    &mut diagnostics,
                );
            }
            // A Markdown template has no markup tree, so "did not parse as
            // markup" is the expected outcome rather than an author error.
            Err(_) if inv.dialect == MacroDialect::Md => {}
            Err(err) => {
                diagnostics.push(parse_error_diag(&display, inv, err.clone()));
            }
        }
    }

    if let Some(file) = parsed_file {
        lint_render_composition(
            &display,
            &file,
            &suppressions,
            &test_ranges,
            &mut diagnostics,
        );
        if !is_generated {
            lint_format_canonicalization(
                &display,
                source,
                &parsed_macros,
                &suppressions,
                &test_ranges,
                &mut diagnostics,
            );
        }
        lint_route_data_loader_items(
            &display,
            &file,
            source,
            &suppressions,
            &test_ranges,
            &mut diagnostics,
        );
        lint_render_impls(
            &display,
            &file,
            &suppressions,
            &test_ranges,
            &mut diagnostics,
        );
        lint_render_functions(
            &display,
            &file,
            &suppressions,
            &test_ranges,
            &mut diagnostics,
        );
        lint_render_helper_definitions(
            &display,
            &file,
            &suppressions,
            &test_ranges,
            &mut diagnostics,
        );
        lint_rsjs_items(
            &display,
            &file,
            rsjs_strategy_cache,
            &suppressions,
            &test_ranges,
            &mut diagnostics,
        );
        lint_attr_value_impls(
            &display,
            &file,
            &suppressions,
            &test_ranges,
            &mut diagnostics,
        );
        lint_render_component_structs(
            &display,
            &file,
            &suppressions,
            &test_ranges,
            &mut diagnostics,
        );
        lint_loop_case_conversions(
            &display,
            &file,
            &suppressions,
            &test_ranges,
            &mut diagnostics,
        );
    }

    dedupe_diagnostics(&mut diagnostics);
    diagnostics
}

pub fn lint_paths(paths: &[std::path::PathBuf], options: LintOptions) -> Result<Vec<Diagnostic>> {
    use rayon::prelude::*;

    let files = crate::source::find_rust_files(paths)?;
    // The sidecar cache is loaded once and shared read-only across workers;
    // loading it per file would re-read and re-parse every sidecar JSON for
    // every source file.
    let rsjs_strategy_cache = options
        .rsjs_strategy_cache
        .as_ref()
        .map(RsjsStrategyCache::load);

    // Files lint independently; par_iter + collect preserves input order, so
    // output stays deterministic regardless of worker scheduling.
    let per_file: Vec<Result<Vec<Diagnostic>>> = files
        .par_iter()
        .map(|path| {
            let source = std::fs::read_to_string(path)
                .with_context(|| format!("failed to read {}", path.display()))?;
            Ok(lint_file_with_cache(
                path,
                &source,
                options.include_tests,
                rsjs_strategy_cache.as_ref(),
            ))
        })
        .collect();

    let mut diagnostics = Vec::new();
    for result in per_file {
        diagnostics.extend(result?);
    }
    diagnostics.extend(content::lint_paths(
        &files,
        options.include_tests,
        &options.content,
    )?);
    Ok(diagnostics)
}

fn lint_format_canonicalization(
    path: &Path,
    source: &str,
    parsed_macros: &[(MacroInvocation, syn::Result<HtmlRoot>)],
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    let rsjs_ranges = crate::fmt::rsjs_line_ranges(source);
    for (inv, parsed) in parsed_macros {
        if line_in_ranges(inv.name_line, ignored_ranges) {
            continue;
        }
        if inv.dialect == MacroDialect::Md {
            let body = inv.body(source);
            if crate::fmt::format_md_body(inv, body) != body {
                push_source_diag_with_severity(
                    path,
                    diagnostics,
                    suppressions,
                    inv.name_line,
                    inv.name_column + 1,
                    Severity::Warning,
                    "format/markdown-layout",
                    "raw Markdown template indentation is not canonical",
                    "run `cargo proa fmt`; the closing `}` belongs on its own line aligned with the Markdown macro invocation",
                );
            }
            continue;
        }
        let Ok(root) = parsed else {
            continue;
        };
        let body = inv.body(source);
        let preserve_legacy_names = line_in_ranges(inv.name_line, &rsjs_ranges);
        let formatted = crate::fmt::format_macro_body(inv, body, root, preserve_legacy_names);
        if formatted != body {
            push_source_diag_with_severity(
                path,
                diagnostics,
                suppressions,
                inv.name_line,
                inv.name_column + 1,
                Severity::Info,
                "format/macro-body",
                "Proa macro body is not in canonical formatter layout",
                "run `cargo proa fmt` to rewrite this macro body",
            );

            if crate::fmt::macro_body_has_noncanonical_expression_layout(
                inv,
                body,
                root,
                preserve_legacy_names,
            ) {
                push_source_diag_with_severity(
                    path,
                    diagnostics,
                    suppressions,
                    inv.name_line,
                    inv.name_column + 1,
                    Severity::Warning,
                    "format/rust-expression-layout",
                    "Rust expressions inside Proa markup are not in canonical layout",
                    "run `cargo proa fmt` to re-indent nested macros and expand overlong struct literals",
                );
            }

            if macro_body_has_attr_spacing(body) {
                push_source_diag_with_severity(
                    path,
                    diagnostics,
                    suppressions,
                    inv.name_line,
                    inv.name_column + 1,
                    Severity::Warning,
                    "format/attrs",
                    "Proa markup uses Rust-style token spacing",
                    "run `cargo proa fmt` to rewrite `< div class = \"x\" >` as `<div class=\"x\">`",
                );
            }

            if macro_body_has_noncanonical_self_closing(body) {
                push_source_diag_with_severity(
                    path,
                    diagnostics,
                    suppressions,
                    inv.name_line,
                    inv.name_column + 1,
                    Severity::Info,
                    "format/self-closing",
                    "self-closing tag spacing is not canonical",
                    "run `cargo proa fmt` to normalize self-closing tags to `<tag />`",
                );
            }
        }
    }
}

fn lint_route_data_loader_items(
    path: &Path,
    file: &File,
    source: &str,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    let has_loader = source.contains("DataLoader") || source.contains("LoaderCache");
    let has_prewarm =
        source.contains("prewarm") || source.contains("warm_cache") || source.contains("warmup");
    lint_route_data_loader_item_list(
        path,
        &file.items,
        has_loader,
        has_prewarm,
        suppressions,
        ignored_ranges,
        diagnostics,
    );
}

fn lint_route_data_loader_item_list(
    path: &Path,
    items: &[Item],
    has_loader: bool,
    has_prewarm: bool,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    for item in items {
        match item {
            Item::Fn(item_fn) => {
                let line = item_fn.sig.ident.span().start().line;
                if line_in_ranges(line, ignored_ranges) {
                    continue;
                }
                check_route_db_load_perf(path, item_fn, has_loader, suppressions, diagnostics);
                check_missing_prewarm_perf(
                    path,
                    item_fn,
                    has_loader,
                    has_prewarm,
                    suppressions,
                    diagnostics,
                );
            }
            Item::Mod(item_mod) => {
                if let Some((_, items)) = &item_mod.content {
                    lint_route_data_loader_item_list(
                        path,
                        items,
                        has_loader,
                        has_prewarm,
                        suppressions,
                        ignored_ranges,
                        diagnostics,
                    );
                }
            }
            _ => {}
        }
    }
}

fn check_route_db_load_perf(
    path: &Path,
    item_fn: &syn::ItemFn,
    has_loader: bool,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    if !has_loader || !is_route_handler_fn(item_fn) {
        return;
    }

    let mut visitor = RouteDbLoadVisitor {
        path,
        suppressions,
        diagnostics,
    };
    visitor.visit_block(&item_fn.block);
}

fn check_missing_prewarm_perf(
    path: &Path,
    item_fn: &syn::ItemFn,
    has_loader: bool,
    has_prewarm: bool,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    if !has_loader || has_prewarm || !is_public_hot_route_fn(item_fn) {
        return;
    }

    push_expr_diag_with_severity(
        path,
        SpanOrigin::File,
        diagnostics,
        suppressions,
        item_fn.sig.ident.span(),
        Severity::Info,
        "route/missing-prewarm",
        "public route appears to use loader-backed data without a prewarm hook",
        "prewarm known public loader requests at startup so first-page SSR does not pay construction cost",
    );
}

struct RouteDbLoadVisitor<'a> {
    path: &'a Path,
    suppressions: &'a SuppressionComments,
    diagnostics: &'a mut Vec<Diagnostic>,
}

impl<'ast> Visit<'ast> for RouteDbLoadVisitor<'_> {
    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        if expr_path_single_ident(&node.receiver).is_some_and(|ident| ident_is_db_handle(&ident))
            && method_name_is_db_load(&node.method.to_string())
        {
            push_expr_diag_with_severity(
                self.path,
                SpanOrigin::File,
                self.diagnostics,
                self.suppressions,
                node.span(),
                Severity::Info,
                "route/direct-db-load",
                "route handler loads data directly even though a DataLoader path exists",
                "load through the cached DataLoader request and render with loader context",
            );
        }
        visit::visit_expr_method_call(self, node);
    }
}

fn lint_render_impls(
    path: &Path,
    file: &File,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    if is_formatter_source_generation_file(path) {
        return;
    }

    lint_render_impl_items(path, &file.items, suppressions, ignored_ranges, diagnostics);
}

fn lint_render_impl_items(
    path: &Path,
    items: &[Item],
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    let helpers = HelperIndex::new(items);
    let markdown_helpers = MarkdownHelperIndex::new(items);
    let render_names = render_component_type_names(items);
    let structs = StructIndex::new(items, &render_names);

    for item in items {
        match item {
            Item::Impl(item_impl) => {
                lint_render_impl(
                    path,
                    item_impl,
                    &helpers,
                    &structs,
                    suppressions,
                    ignored_ranges,
                    diagnostics,
                );
                lint_markdown_render_impl(
                    path,
                    item_impl,
                    &markdown_helpers,
                    suppressions,
                    ignored_ranges,
                    diagnostics,
                );
            }
            Item::Mod(item_mod) => {
                if let Some((_, items)) = &item_mod.content {
                    lint_render_impl_items(path, items, suppressions, ignored_ranges, diagnostics);
                }
            }
            _ => {}
        }
    }
}

fn lint_render_impl(
    path: &Path,
    item_impl: &ItemImpl,
    helpers: &HelperIndex<'_>,
    structs: &StructIndex,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    match &item_impl.trait_ {
        Some((_, trait_path, _)) if is_render_trait(trait_path) => {}
        _ => return,
    }

    for item in &item_impl.items {
        let ImplItem::Fn(method) = item else {
            continue;
        };
        if method.sig.ident != "render" {
            continue;
        }
        let line = method.sig.ident.span().start().line;
        if line_in_ranges(line, ignored_ranges) {
            continue;
        }
        check_render_block_perf(path, &method.block, suppressions, diagnostics, true);
        check_render_api_perf(path, item_impl, method, suppressions, diagnostics);
        check_owned_view_model_perf(path, &method.block, structs, suppressions, diagnostics);
        check_large_render_clone_perf(path, &method.block, suppressions, diagnostics);
        check_direct_helper_perf(
            path,
            &method.block,
            helpers,
            suppressions,
            ignored_ranges,
            diagnostics,
            true,
        );
    }
}

fn lint_markdown_render_impl(
    path: &Path,
    item_impl: &ItemImpl,
    helpers: &MarkdownHelperIndex<'_>,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    let Some((_, trait_path, _)) = &item_impl.trait_ else {
        return;
    };
    if !is_markdown_render_trait(trait_path) {
        return;
    }

    for item in &item_impl.items {
        let ImplItem::Fn(method) = item else {
            continue;
        };
        if method.sig.ident != "render_md" {
            continue;
        }
        let line = method.sig.ident.span().start().line;
        if line_in_ranges(line, ignored_ranges) {
            continue;
        }

        check_markdown_render_api_perf(path, item_impl, method, suppressions, diagnostics);

        let mut visited = HashSet::new();
        check_markdown_block_writes(
            path,
            &method.block,
            helpers,
            suppressions,
            ignored_ranges,
            diagnostics,
            &mut visited,
        );
    }
}

/// Markdown mirror of [`check_render_api_perf`].
///
/// `md!` lowers to `async_md_from_fn(Box::new(|cx| Box::pin(async move
/// { .. })))` exactly like async `html!`, while `md_sync!` lowers to an
/// unboxed `OptimizedMd`, so the same two rules apply.
fn check_markdown_render_api_perf(
    path: &Path,
    item_impl: &ItemImpl,
    method: &syn::ImplItemFn,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    let Some((_, trait_path, _)) = &item_impl.trait_ else {
        return;
    };
    if path_last_ident(trait_path).as_deref() != Some("MdRender") {
        return;
    }

    let has_async_child_bound = generics_bind_async_render(&item_impl.generics, &["MdRender"])
        || generics_bind_async_render(&method.sig.generics, &["MdRender"]);
    if has_async_child_bound {
        return;
    }

    if !block_completes_render_outcome_done(&method.block)
        && !block_forwards_foreign_render_outcome(&method.block)
        && !block_contains_await(&method.block)
        && !block_contains_md_async_render_marker(&method.block)
    {
        push_expr_diag(
            path,
            SpanOrigin::File,
            diagnostics,
            suppressions,
            method.sig.ident.span(),
            "render/md-async-unneeded",
            "MdRender implementation does not await async work",
            "implement MdRenderSync unless the component truly needs async rendering",
        );
    }

    check_async_md_static_body(path, &method.block, suppressions, diagnostics);
}

/// Flag `md!` invocations with no async work in the body.
///
/// `md!` template bodies are one raw string literal, so slot expressions never
/// reach the token stream as idents; the literal itself is scanned for
/// `.await` as well.
fn check_async_md_static_body(
    path: &Path,
    block: &Block,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    struct Visitor<'a> {
        path: &'a Path,
        suppressions: &'a SuppressionComments,
        diagnostics: &'a mut Vec<Diagnostic>,
    }

    impl<'ast> Visit<'ast> for Visitor<'_> {
        fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
            if macro_path_ends(node, "md") {
                let tokens = &node.mac.tokens;
                let has_async = tokens_mention_ident(tokens, &["await"])
                    || tokens_mention_ident(tokens, MD_ASYNC_RENDER_MARKERS)
                    || tokens_contain_await_in_literal(tokens);
                if !has_async {
                    push_expr_diag(
                        self.path,
                        SpanOrigin::File,
                        self.diagnostics,
                        self.suppressions,
                        node.mac.path.span(),
                        "perf/async-md-static-subtree",
                        "async md! template has no async interpolation",
                        "use md_sync! here; wrap the result with proa_core::to_md_async(...) if it is composed into an async tree",
                    );
                }
            }
            visit::visit_expr_macro(self, node);
        }
    }

    let mut visitor = Visitor {
        path,
        suppressions,
        diagnostics,
    };
    visitor.visit_block(block);
}

#[allow(clippy::too_many_arguments)]
fn check_markdown_block_writes(
    path: &Path,
    block: &Block,
    helpers: &MarkdownHelperIndex<'_>,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
    visited: &mut HashSet<String>,
) {
    {
        let mut visitor = MarkdownRenderVisitor {
            path,
            suppressions,
            diagnostics,
        };
        visitor.visit_block(block);
    }

    for helper_name in MarkdownHelperCalls::collect(block) {
        let Some(helper) = helpers.get(&helper_name) else {
            continue;
        };
        if !visited.insert(helper_name) {
            continue;
        }
        let line = helper.brace_token.span.open().start().line;
        if line_in_ranges(line, ignored_ranges) {
            continue;
        }
        check_markdown_block_writes(
            path,
            helper,
            helpers,
            suppressions,
            ignored_ranges,
            diagnostics,
            visited,
        );
    }
}

struct MarkdownHelperIndex<'a> {
    blocks: HashMap<String, &'a Block>,
}

impl<'a> MarkdownHelperIndex<'a> {
    fn new(items: &'a [Item]) -> Self {
        let mut blocks = HashMap::new();
        for item in items {
            match item {
                Item::Fn(item_fn) => {
                    blocks.insert(item_fn.sig.ident.to_string(), item_fn.block.as_ref());
                }
                Item::Impl(item_impl) if item_impl.trait_.is_none() => {
                    for impl_item in &item_impl.items {
                        if let ImplItem::Fn(method) = impl_item {
                            blocks.insert(method.sig.ident.to_string(), &method.block);
                        }
                    }
                }
                _ => {}
            }
        }
        Self { blocks }
    }

    fn get(&self, name: &str) -> Option<&'a Block> {
        self.blocks.get(name).copied()
    }
}

struct MarkdownHelperCalls {
    names: HashSet<String>,
}

impl MarkdownHelperCalls {
    fn collect(block: &Block) -> HashSet<String> {
        let mut collector = Self {
            names: HashSet::new(),
        };
        collector.visit_block(block);
        collector.names
    }
}

impl<'ast> Visit<'ast> for MarkdownHelperCalls {
    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if let Expr::Path(path) = node.func.as_ref() {
            let segments = &path.path.segments;
            let is_direct = segments.len() == 1;
            let is_self_associated = segments.len() == 2
                && segments
                    .first()
                    .is_some_and(|segment| segment.ident == "Self");
            if is_direct || is_self_associated {
                if let Some(segment) = segments.last() {
                    self.names.insert(segment.ident.to_string());
                }
            }
        }
        visit::visit_expr_call(self, node);
    }

    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        if expr_path_single_ident(&node.receiver).is_some_and(|ident| ident == "self") {
            self.names.insert(node.method.to_string());
        }
        visit::visit_expr_method_call(self, node);
    }
}

struct MarkdownRenderVisitor<'a> {
    path: &'a Path,
    suppressions: &'a SuppressionComments,
    diagnostics: &'a mut Vec<Diagnostic>,
}

impl<'ast> Visit<'ast> for MarkdownRenderVisitor<'_> {
    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        let is_raw_output_write = match node.func.as_ref() {
            Expr::Path(path) => {
                let method = path
                    .path
                    .segments
                    .last()
                    .map(|segment| segment.ident.to_string());
                method.is_some_and(|method| {
                    matches!(
                        method.as_str(),
                        "extend" | "extend_static" | "extend_shared" | "extend_with"
                    )
                }) && node.args.first().is_some_and(expr_is_markdown_output)
            }
            _ => false,
        };

        if is_raw_output_write {
            push_manual_markdown_write(self.path, self.diagnostics, self.suppressions, node.span());
        }
        visit::visit_expr_call(self, node);
    }

    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        let method = node.method.to_string();
        let is_raw_context_write = matches!(
            method.as_str(),
            "write_md_prepared_static"
                | "write_md_prepared"
                | "write_md_prepared_str"
                | "write_md_prepared_shared"
        ) || (matches!(method.as_str(), "write" | "write_str")
            && expr_is_markdown_context(&node.receiver));
        let is_raw_output_write = matches!(
            method.as_str(),
            "extend" | "extend_static" | "extend_shared" | "extend_with"
        ) && expr_is_markdown_output(&node.receiver);

        if is_raw_context_write || is_raw_output_write {
            push_manual_markdown_write(self.path, self.diagnostics, self.suppressions, node.span());
        }
        visit::visit_expr_method_call(self, node);
    }
}

fn push_manual_markdown_write(
    path: &Path,
    diagnostics: &mut Vec<Diagnostic>,
    suppressions: &SuppressionComments,
    span: proc_macro2::Span,
) {
    push_expr_diag_with_severity(
        path,
        SpanOrigin::File,
        diagnostics,
        suppressions,
        span,
        Severity::Warning,
        "md/manual-write",
        "Markdown bytes are written by hand inside a Markdown renderer",
        "render static and interpolated Markdown with `md_sync! { r###\"...\"### }.render_md(cx)`; use typed `WebContext` helpers such as `write_md_text`, `write_md_url`, `md_code`, or `md_link` when the value needs Markdown-specific escaping",
    );
}

fn expr_is_markdown_context(expr: &Expr) -> bool {
    match expr {
        Expr::Group(group) => expr_is_markdown_context(&group.expr),
        Expr::Paren(paren) => expr_is_markdown_context(&paren.expr),
        Expr::Path(path) => path.path.segments.last().is_some_and(|segment| {
            matches!(
                segment.ident.to_string().as_str(),
                "cx" | "ctx" | "context" | "md_context"
            )
        }),
        _ => false,
    }
}

fn expr_is_markdown_output(expr: &Expr) -> bool {
    match expr {
        Expr::Group(group) => expr_is_markdown_output(&group.expr),
        Expr::Paren(paren) => expr_is_markdown_output(&paren.expr),
        Expr::Reference(reference) => expr_is_markdown_output(&reference.expr),
        Expr::Field(field) => {
            matches!(&field.member, syn::Member::Named(name) if name == "out")
                && expr_is_markdown_context(&field.base)
        }
        _ => false,
    }
}

// ---------------------------------------------------------------------------
// perf/render-copy: pre-rendered output re-embedded into another render.
//
// The two-phase pattern (render a fragment to a String, then splice it into
// a second render via UnsafeRaw / push_str / another render_* call) copies
// the fragment bytes at least twice per request. It is the natural first
// shape for page composition and exactly what a generic component slot
// eliminates, so it gets its own rule with restructure guidance. The pass
// runs over every function (routes and helpers included), not just
// classified render entries, because the antipattern lives at the
// composition layer.
// ---------------------------------------------------------------------------

fn lint_render_composition(
    path: &Path,
    file: &File,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    if is_formatter_source_generation_file(path) {
        return;
    }

    fn walk_items(
        path: &Path,
        items: &[Item],
        suppressions: &SuppressionComments,
        ignored_ranges: &[RangeInclusive<usize>],
        diagnostics: &mut Vec<Diagnostic>,
    ) {
        for item in items {
            match item {
                Item::Fn(item_fn) => {
                    let line = item_fn.sig.ident.span().start().line;
                    if !line_in_ranges(line, ignored_ranges) {
                        check_block_render_composition(
                            path,
                            &item_fn.block,
                            suppressions,
                            diagnostics,
                        );
                    }
                }
                Item::Impl(item_impl) => {
                    for impl_item in &item_impl.items {
                        if let ImplItem::Fn(method) = impl_item {
                            let line = method.sig.ident.span().start().line;
                            if !line_in_ranges(line, ignored_ranges) {
                                check_block_render_composition(
                                    path,
                                    &method.block,
                                    suppressions,
                                    diagnostics,
                                );
                            }
                        }
                    }
                }
                Item::Mod(item_mod) => {
                    if let Some((_, inner)) = &item_mod.content {
                        walk_items(path, inner, suppressions, ignored_ranges, diagnostics);
                    }
                }
                _ => {}
            }
        }
    }
    walk_items(path, &file.items, suppressions, ignored_ranges, diagnostics);
}

fn is_formatter_source_generation_file(path: &Path) -> bool {
    let mut components = path
        .components()
        .filter_map(|component| component.as_os_str().to_str());
    components.any(|component| component == "proa_cli")
        && path.file_name().and_then(|name| name.to_str()) == Some("fmt.rs")
}

/// Does this call produce rendered output as an owned buffer?
fn call_is_render_to_buffer(call: &ExprCall) -> bool {
    let Some(seg) = call_last_segment(call) else {
        return false;
    };
    matches!(
        seg.as_str(),
        "render_to_string" | "try_render_to_string" | "render_to_vec"
    ) || (seg.starts_with("render")
        && (seg.contains("to_string") || seg.contains("to_vec") || seg.contains("capturing")))
}

fn call_last_segment(call: &ExprCall) -> Option<String> {
    if let Expr::Path(expr_path) = call.func.as_ref() {
        return expr_path
            .path
            .segments
            .last()
            .map(|seg| seg.ident.to_string());
    }
    None
}

/// Collect identifiers referenced anywhere inside an expression.
fn expr_mentions_ident(expr: &Expr, idents: &HashSet<String>) -> bool {
    struct Finder<'a> {
        idents: &'a HashSet<String>,
        found: bool,
    }
    impl<'ast> Visit<'ast> for Finder<'_> {
        fn visit_expr_path(&mut self, node: &'ast ExprPath) {
            if let Some(ident) = node.path.get_ident() {
                if self.idents.contains(&ident.to_string()) {
                    self.found = true;
                }
            }
            visit::visit_expr_path(self, node);
        }
    }
    let mut finder = Finder {
        idents,
        found: false,
    };
    finder.visit_expr(expr);
    finder.found
}

fn check_block_render_composition(
    path: &Path,
    block: &Block,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    struct CompositionVisitor<'a> {
        path: &'a Path,
        suppressions: &'a SuppressionComments,
        diagnostics: &'a mut Vec<Diagnostic>,
        rendered_locals: HashSet<String>,
    }

    impl<'ast> Visit<'ast> for CompositionVisitor<'_> {
        fn visit_local(&mut self, node: &'ast Local) {
            if let Some(init) = &node.init {
                let mut init_expr = init.expr.as_ref();
                while let Expr::Reference(reference) = init_expr {
                    init_expr = reference.expr.as_ref();
                }
                if let Expr::Call(call) = init_expr {
                    if call_is_render_to_buffer(call) {
                        match &node.pat {
                            Pat::Ident(pat_ident) => {
                                self.rendered_locals.insert(pat_ident.ident.to_string());
                            }
                            Pat::Tuple(tuple) => {
                                for elem in &tuple.elems {
                                    if let Pat::Ident(pat_ident) = elem {
                                        self.rendered_locals.insert(pat_ident.ident.to_string());
                                    }
                                }
                            }
                            _ => {}
                        }
                    }
                }
            }
            visit::visit_local(self, node);
        }

        fn visit_expr_call(&mut self, node: &'ast ExprCall) {
            if is_perf_suppressed_call(node) {
                return;
            }
            let seg = call_last_segment(node);
            let mentions = node
                .args
                .iter()
                .any(|arg| expr_mentions_ident(arg, &self.rendered_locals));
            if mentions {
                if seg.as_deref() == Some("UnsafeRaw") {
                    push_expr_diag(
                        self.path,
                        SpanOrigin::File,
                        self.diagnostics,
                        self.suppressions,
                        node.span(),
                        "perf/render-copy",
                        "pre-rendered output is spliced into another render via UnsafeRaw, copying the bytes again",
                        "render in a single pass: give the outer component a generic slot (river/tail style) and render the inner component inline",
                    );
                } else if seg.as_deref().is_some_and(|name| {
                    name.starts_with("render") && !call_is_render_to_buffer(node)
                }) {
                    push_expr_diag(
                        self.path,
                        SpanOrigin::File,
                        self.diagnostics,
                        self.suppressions,
                        node.span(),
                        "perf/render-copy",
                        "pre-rendered output is passed into another render, copying the bytes again",
                        "compose components instead of strings: pass the inner component through a generic slot so both render in one pass",
                    );
                }
            }
            visit::visit_expr_call(self, node);
        }

        fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
            if node.method == "push_str"
                && node
                    .args
                    .iter()
                    .any(|arg| expr_mentions_ident(arg, &self.rendered_locals))
            {
                push_expr_diag(
                    self.path,
                    SpanOrigin::File,
                    self.diagnostics,
                    self.suppressions,
                    node.span(),
                    "perf/render-copy",
                    "rendered output is concatenated into another buffer, copying the bytes again",
                    "render in a single pass: emit directly into one buffer via component slots instead of assembling strings",
                );
            }
            // Hand-assembled HTML anywhere (routes and helpers included):
            // String concatenation of markup bypasses both escaping and
            // compile-time consolidation.
            if node.method == "push_str" && node.args.iter().any(expr_is_html_literal) {
                push_expr_diag(
                    self.path,
                    SpanOrigin::File,
                    self.diagnostics,
                    self.suppressions,
                    node.span(),
                    "perf/raw-html-buffer",
                    "HTML is assembled by hand outside the template system, bypassing escaping and consolidation",
                    "build the fragment with html_sync!/html! and render it through a component; for a trusted low-level emitter add `// proa-perf-ok(scope): reason`",
                );
            }
            visit::visit_expr_method_call(self, node);
        }

        fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
            let is_writer = node.mac.path.segments.last().is_some_and(|seg| {
                matches!(
                    seg.ident.to_string().as_str(),
                    "write" | "writeln" | "format"
                )
            });
            if is_writer && tokens_contain_html_literal(&node.mac.tokens) {
                push_expr_diag(
                    self.path,
                    SpanOrigin::File,
                    self.diagnostics,
                    self.suppressions,
                    node.span(),
                    "perf/raw-html-buffer",
                    "HTML is assembled by hand outside the template system, bypassing escaping and consolidation",
                    "build the fragment with html_sync!/html! and render it through a component; for a trusted low-level emitter add `// proa-perf-ok(scope): reason`",
                );
            }
            visit::visit_expr_macro(self, node);
        }
    }

    let mut visitor = CompositionVisitor {
        path,
        suppressions,
        diagnostics,
        rendered_locals: HashSet::new(),
    };
    visitor.visit_block(block);
}

fn lint_render_functions(
    path: &Path,
    file: &File,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    if is_formatter_source_generation_file(path) {
        return;
    }

    lint_render_function_items(path, &file.items, suppressions, ignored_ranges, diagnostics);
}

fn lint_render_function_items(
    path: &Path,
    items: &[Item],
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    let helpers = HelperIndex::new(items);
    for item in items {
        match item {
            Item::Fn(item_fn) if function_is_standalone_render_entry(item_fn) => {
                let line = item_fn.sig.ident.span().start().line;
                if line_in_ranges(line, ignored_ranges) {
                    continue;
                }
                let html = standalone_renders_html(item_fn);
                check_render_block_perf(path, &item_fn.block, suppressions, diagnostics, html);
                check_direct_helper_perf(
                    path,
                    &item_fn.block,
                    &helpers,
                    suppressions,
                    ignored_ranges,
                    diagnostics,
                    html,
                );
            }
            Item::Mod(item_mod) => {
                if let Some((_, items)) = &item_mod.content {
                    lint_render_function_items(
                        path,
                        items,
                        suppressions,
                        ignored_ranges,
                        diagnostics,
                    );
                }
            }
            _ => {}
        }
    }
}

fn function_is_standalone_render_entry(item_fn: &syn::ItemFn) -> bool {
    item_fn.sig.ident.to_string().starts_with("render_")
        && (function_has_web_context_param(item_fn) || block_constructs_web_context(&item_fn.block))
}

/// Preserve HTML checks for standalone render helpers, including raw byte
/// writers. Markdown evidence opts out of HTML-specific guidance; allocation
/// checks still apply to both representations.
fn standalone_renders_html(item_fn: &syn::ItemFn) -> bool {
    let name = item_fn.sig.ident.to_string();
    if name.starts_with("render_md") || name.starts_with("render_markdown") {
        return false;
    }
    fn is_markdown_operation(name: &str) -> bool {
        name == "render_md"
            || name == "render_markdown"
            || name.starts_with("write_md_")
            || name.starts_with("md_")
    }
    struct MarkdownUse(bool);
    impl<'ast> Visit<'ast> for MarkdownUse {
        fn visit_macro(&mut self, node: &'ast syn::Macro) {
            if node.path.segments.last().is_some_and(|segment| {
                matches!(segment.ident.to_string().as_str(), "md" | "md_sync")
            }) {
                self.0 = true;
            }
            visit::visit_macro(self, node);
        }
        fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
            if is_markdown_operation(&node.method.to_string()) {
                self.0 = true;
            }
            visit::visit_expr_method_call(self, node);
        }
        fn visit_expr_call(&mut self, node: &'ast ExprCall) {
            if let Expr::Path(path) = node.func.as_ref() {
                if path
                    .path
                    .segments
                    .last()
                    .is_some_and(|segment| is_markdown_operation(&segment.ident.to_string()))
                {
                    self.0 = true;
                }
            }
            visit::visit_expr_call(self, node);
        }
    }
    let mut evidence = MarkdownUse(false);
    evidence.visit_block(&item_fn.block);
    !evidence.0
}

fn function_has_web_context_param(item_fn: &syn::ItemFn) -> bool {
    item_fn.sig.inputs.iter().any(|arg| {
        let syn::FnArg::Typed(pat_ty) = arg else {
            return false;
        };
        type_path_last_ident(&pat_ty.ty).is_some_and(|name| {
            matches!(
                name.as_str(),
                "WebContext" | "LatencyWebContext" | "RouteWebContext" | "StaticWebContext"
            )
        })
    })
}

fn block_constructs_web_context(block: &Block) -> bool {
    struct Finder {
        found: bool,
    }

    impl<'ast> Visit<'ast> for Finder {
        fn visit_expr_call(&mut self, node: &'ast ExprCall) {
            if call_path_ends(node, &["StaticWebContext", "new"])
                || call_path_ends(node, &["WebContext", "new"])
                || call_path_ends(node, &["WebContext", "with_buffer"])
                || call_path_ends(node, &["WebContext", "with_loader"])
                || call_path_ends(node, &["WebContext", "with_loader_buffer"])
                || call_path_ends(node, &["LatencyWebContext", "new"])
                || call_path_ends(node, &["RouteWebContext", "new"])
            {
                self.found = true;
                return;
            }
            visit::visit_expr_call(self, node);
        }
    }

    let mut finder = Finder { found: false };
    finder.visit_block(block);
    finder.found
}

fn lint_render_helper_definitions(
    path: &Path,
    file: &File,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    if is_formatter_source_generation_file(path) {
        return;
    }

    lint_render_helper_definition_items(
        path,
        &file.items,
        suppressions,
        ignored_ranges,
        diagnostics,
    );
}

fn lint_render_helper_definition_items(
    path: &Path,
    items: &[Item],
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    if item_list_has_render_surface(items) {
        for item in items {
            let Item::Fn(item_fn) = item else {
                continue;
            };
            let line = item_fn.sig.ident.span().start().line;
            if line_in_ranges(line, ignored_ranges) {
                continue;
            }
            check_render_helper_definition_perf(path, item_fn, suppressions, diagnostics);
        }
    }

    for item in items {
        let Item::Mod(item_mod) = item else {
            continue;
        };
        if let Some((_, items)) = &item_mod.content {
            lint_render_helper_definition_items(
                path,
                items,
                suppressions,
                ignored_ranges,
                diagnostics,
            );
        }
    }
}

fn item_list_has_render_surface(items: &[Item]) -> bool {
    items.iter().any(
        |item| matches!(item, Item::Impl(item_impl) if render_impl_self_name(item_impl).is_some()),
    )
}

fn check_render_helper_definition_perf(
    path: &Path,
    item_fn: &syn::ItemFn,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    if !return_type_is_owned_string(&item_fn.sig.output) {
        return;
    }

    let name = item_fn.sig.ident.to_string();
    if helper_name_is_manual_escape(&name) && block_has_manual_escape_helper_shape(&item_fn.block) {
        push_expr_diag(
            path,
            SpanOrigin::File,
            diagnostics,
            suppressions,
            item_fn.sig.ident.span(),
            "perf/manual-escape-helper",
            "String-returning manual escape helper lives next to Proa render code",
            "delete the helper and let html_sync!/AttrValue rendering escape text and attributes",
        );
    }

    if helper_name_is_html_string_builder(&name) && block_contains_html_literal(&item_fn.block) {
        push_expr_diag(
            path,
            SpanOrigin::File,
            diagnostics,
            suppressions,
            item_fn.sig.ident.span(),
            "perf/raw-html-buffer",
            "String-returning helper assembles HTML outside the template engine",
            "return a WebRenderSync component and write the markup with html_sync! instead of feeding HTML through UnsafeRaw",
        );
    }
}

fn lint_rsjs_items(
    path: &Path,
    file: &File,
    strategy_cache: Option<&RsjsStrategyCache>,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    lint_rsjs_item_list(
        path,
        &file.items,
        false,
        strategy_cache,
        suppressions,
        ignored_ranges,
        diagnostics,
    );
}

fn lint_rsjs_item_list(
    path: &Path,
    items: &[Item],
    in_client_module: bool,
    strategy_cache: Option<&RsjsStrategyCache>,
    suppressions: &SuppressionComments,
    ignored_ranges: &[RangeInclusive<usize>],
    diagnostics: &mut Vec<Diagnostic>,
) {
    for item in items {
        match item {
            Item::Impl(item_impl) if has_attr(&item_impl.attrs, &["rsjs"]) => {
                if let Some(span) = removed_rsjs_clients_arg_span(&item_impl.attrs) {
                    push_expr_diag_with_severity(
                        path,
                        SpanOrigin::File,
                        diagnostics,
                        suppressions,
                        span,
                        Severity::Error,
                        "rsjs/removed-clients-allowlist",
                        "`clients(...)` was removed from `#[rsjs(...)]`",
                        "remove `clients(...)`; annotate each portable helper definition once \
                         with `#[rsjs::client]` and call it through an ordinary Rust path. \
                         Reachable calls are linked automatically, while \
                         `#[rsjs::client_module]` remains optional grouping",
                    );
                }
                for item in &item_impl.items {
                    let ImplItem::Fn(method) = item else {
                        continue;
                    };
                    if method.sig.ident != "render" {
                        continue;
                    }
                    let line = method.sig.ident.span().start().line;
                    if line_in_ranges(line, ignored_ranges) {
                        continue;
                    }
                    check_rsjs_block(path, &method.block, suppressions, diagnostics);
                    check_unused_rsjs_named_client_locals(
                        path,
                        &method.block,
                        suppressions,
                        diagnostics,
                    );
                    check_rsjs_component_analysis(
                        path,
                        item_impl,
                        method,
                        strategy_cache,
                        suppressions,
                        diagnostics,
                    );
                }
            }
            Item::Impl(item_impl) if in_client_module => {
                for item in &item_impl.items {
                    let ImplItem::Fn(method) = item else {
                        continue;
                    };
                    let line = method.sig.ident.span().start().line;
                    if line_in_ranges(line, ignored_ranges) {
                        continue;
                    }
                    check_rsjs_block(path, &method.block, suppressions, diagnostics);
                }
            }
            Item::Fn(item_fn)
                if in_client_module || has_attr(&item_fn.attrs, &["rsjs", "client"]) =>
            {
                let line = item_fn.sig.ident.span().start().line;
                if line_in_ranges(line, ignored_ranges) {
                    continue;
                }
                check_rsjs_block(path, &item_fn.block, suppressions, diagnostics);
            }
            Item::Mod(item_mod) => {
                if let Some((_, items)) = &item_mod.content {
                    let is_client_module = in_client_module
                        || has_attr(&item_mod.attrs, &["rsjs", "client_module"])
                        || has_attr(&item_mod.attrs, &["rsjs", "client"]);
                    lint_rsjs_item_list(
                        path,
                        items,
                        is_client_module,
                        strategy_cache,
                        suppressions,
                        ignored_ranges,
                        diagnostics,
                    );
                }
            }
            _ => {}
        }
    }
}

fn check_rsjs_block(
    path: &Path,
    block: &Block,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    let mut visitor = RsjsVisitor {
        path,
        suppressions,
        diagnostics,
        signals: HashSet::new(),
        handlers: HashSet::new(),
        client_locals: HashSet::new(),
        derived_client_locals: HashSet::new(),
        unsupported_client_aliases: HashMap::new(),
        shared_state_locals: HashSet::new(),
        shared_field_locals: HashSet::new(),
    };
    visitor.visit_block(block);
}

struct RsjsAttrArgs {
    removed_clients_span: Option<proc_macro2::Span>,
}

impl syn::parse::Parse for RsjsAttrArgs {
    fn parse(input: syn::parse::ParseStream<'_>) -> syn::Result<Self> {
        let mut removed_clients_span = None;
        while !input.is_empty() {
            let key: syn::Ident = input.parse()?;
            if key == "clients" {
                let content;
                syn::parenthesized!(content in input);
                let _: Punctuated<SynPath, Token![,]> =
                    content.parse_terminated(SynPath::parse_mod_style, Token![,])?;
                removed_clients_span.get_or_insert(key.span());
            } else if key == "strategy" || key == "render" || key == "fallback" {
                let _: Token![=] = input.parse()?;
                let _: Lit = input.parse()?;
            } else if key == "client_only" {
                // The macro rejects this policy today. Keep the source
                // lint tolerant so rustc owns the user-facing parse error.
            } else if key == "component" {
                // Component marker has no client-module paths of its own.
            } else if key == "client" {
                // Origin permission has no client-module paths of its own.
            } else {
                return Err(syn::Error::new(
                    key.span(),
                    "unsupported rsjs attribute argument",
                ));
            }
            if input.peek(Token![,]) {
                let _: Token![,] = input.parse()?;
            }
        }
        Ok(Self {
            removed_clients_span,
        })
    }
}

fn removed_rsjs_clients_arg_span(attrs: &[SynAttribute]) -> Option<proc_macro2::Span> {
    attrs.iter().find_map(|attr| {
        if !has_attr(std::slice::from_ref(attr), &["rsjs"]) {
            return None;
        }
        let syn::Meta::List(list) = &attr.meta else {
            return None;
        };
        syn::parse2::<RsjsAttrArgs>(list.tokens.clone())
            .ok()
            .and_then(|args| args.removed_clients_span)
    })
}

fn check_rsjs_component_analysis(
    path: &Path,
    item_impl: &ItemImpl,
    method: &syn::ImplItemFn,
    strategy_cache: Option<&RsjsStrategyCache>,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    if let Some(cache) = strategy_cache {
        match cache.lookup_impl(item_impl) {
            RsjsStrategyMatch::Found(sidecar) => {
                push_rsjs_unused_client_module_diag(
                    path,
                    method,
                    sidecar,
                    suppressions,
                    diagnostics,
                );
                push_rsjs_unnecessary_server_only_from_sidecar(
                    path,
                    method,
                    sidecar,
                    suppressions,
                    diagnostics,
                );
                push_rsjs_client_crossings_from_sidecar(
                    path,
                    method,
                    sidecar,
                    suppressions,
                    diagnostics,
                );
                push_rsjs_dead_client_primitives_from_sidecar(
                    path,
                    method,
                    sidecar,
                    suppressions,
                    diagnostics,
                );
                push_rsjs_component_fragment_mounts_from_sidecar(
                    path,
                    method,
                    sidecar,
                    suppressions,
                    diagnostics,
                );
                if sidecar.render_strategy == "server_only"
                    && sidecar
                        .hydration_strategy_kind
                        .as_deref()
                        .is_some_and(|kind| kind != "immediate")
                {
                    // proa-perf-ok: CLI diagnostic text, not rendered HTML
                    let help = format!(
                        "`strategy = \"{}\"` only controls when browser JS hydrates, and this render method emits no browser JS",
                        sidecar
                            .hydration_strategy_label
                            .as_deref()
                            .unwrap_or("<unknown>")
                    );
                    push_expr_diag(
                        path,
                        SpanOrigin::File,
                        diagnostics,
                        suppressions,
                        method.sig.ident.span(),
                        "rsjs/ignored-hydration-strategy",
                        "hydration strategy is ignored because this RSJS-analyzed render method is ServerOnly",
                        &help,
                    );
                }
            }
            RsjsStrategyMatch::Missing if cache.require_fresh => {
                push_rsjs_strategy_cache_diag(
                    path,
                    method,
                    suppressions,
                    diagnostics,
                    Severity::Error,
                    "rsjs/strategy-cache-missing",
                    "no matching rsjs strategy sidecar was found for this analyzed component render impl",
                    "run a build that emits target/rsjs/strategy/*.json, or remove --require-fresh-strategy-cache",
                );
            }
            RsjsStrategyMatch::Stale(matches) if cache.require_fresh => {
                let help = format!(
                    "found {} sidecar(s) for this impl, but their input_fingerprint does not match the current source; rebuild or clear target/rsjs/strategy",
                    matches.len()
                );
                push_rsjs_strategy_cache_diag(
                    path,
                    method,
                    suppressions,
                    diagnostics,
                    Severity::Error,
                    "rsjs/strategy-cache-stale",
                    "matching rsjs strategy sidecar is stale for this analyzed component render impl",
                    &help,
                );
            }
            RsjsStrategyMatch::Ambiguous(matches) if cache.require_fresh => {
                let help = format!(
                    "found {} matching sidecars; pass a narrower lint path after a clean build or clear target/rsjs/strategy",
                    matches.len()
                );
                push_rsjs_strategy_cache_diag(
                    path,
                    method,
                    suppressions,
                    diagnostics,
                    Severity::Error,
                    "rsjs/strategy-cache-ambiguous",
                    "multiple rsjs strategy sidecars match this analyzed component render impl",
                    &help,
                );
            }
            RsjsStrategyMatch::Missing
            | RsjsStrategyMatch::Stale(_)
            | RsjsStrategyMatch::Ambiguous(_) => {
                // Non-strict cache mode falls back to the conservative
                // source heuristic below.
            }
        }
    }

    // A participant-only `#[rsjs(component)]` may intentionally emit no
    // browser JavaScript while still publishing the component ABI required by
    // a live parent. Source-only analysis cannot prove the attribute is
    // unnecessary, so do not recommend deleting it.
}

fn push_rsjs_unnecessary_server_only_from_sidecar(
    path: &Path,
    method: &syn::ImplItemFn,
    sidecar: &crate::rsjs::StrategySidecarSummary,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    for surface in &sidecar.server_surfaces {
        if surface.source.as_deref() != Some("explicit_simple_ssr_boundary") {
            continue;
        }
        let Some(anchor) = &surface.source_anchor else {
            continue;
        };
        if !sidecar_surface_anchor_is_in_method(anchor, method) {
            continue;
        }
        if sidecar_boundary_is_inbound_snapshot(anchor, method) {
            // `self.field` is a latent LiveRead in an analyzed component.
            // Removing this explicit wrapper would change semantics from a
            // per-render snapshot to a live composed prop, so it is never an
            // "unnecessary" boundary even though the frontend can render it
            // as a simple SSR projection.
            continue;
        }
        if diagnostics.iter().any(|diag| {
            diag.code == "rsjs/unnecessary-server-only"
                && diag.line == anchor.start_line
                && diag.column == anchor.start_column
        }) {
            continue;
        }
        let help = match surface.kind.as_str() {
            "server_attr" => {
                "remove `rsjs::server_attr(...)`; simple literals, ordinary locals, and their field projections render as server-only attributes in v2"
            }
            _ => {
                "remove `rsjs::server_only(...)`; simple literals, ordinary locals, and their field projections render on the server in v2"
            }
        };
        push_source_diag_with_severity(
            path,
            diagnostics,
            suppressions,
            anchor.start_line,
            anchor.start_column,
            Severity::Warning,
            "rsjs/unnecessary-server-only",
            "compiler strategy found an unnecessary explicit server boundary around a simple SSR value",
            help,
        );
    }
}

fn push_rsjs_client_crossings_from_sidecar(
    path: &Path,
    method: &syn::ImplItemFn,
    sidecar: &crate::rsjs::StrategySidecarSummary,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    for crossing in &sidecar.crossings {
        let Some(anchor) = &crossing.source_anchor else {
            continue;
        };
        if !client_crossing_anchor_is_in_method(anchor, method) {
            continue;
        }
        let requirement = crossing.requirement.as_deref().unwrap_or("client_encode");
        let message = crate::rsjs::client_crossing_summary_detail(crossing);
        let help = format!(
            "this value is serialized for reachable Client IR and must satisfy `{requirement}`; render it through SSR/server_only if it should remain server-private"
        );
        if diagnostics.iter().any(|diag| {
            diag.code == "rsjs/client-crossing"
                && diag.line == anchor.start_line
                && diag.column == anchor.start_column
                && diag.message == message
        }) {
            continue;
        }
        push_source_diag_with_severity(
            path,
            diagnostics,
            suppressions,
            anchor.start_line,
            anchor.start_column,
            Severity::Info,
            "rsjs/client-crossing",
            &message,
            &help,
        );
    }
}

fn push_rsjs_dead_client_primitives_from_sidecar(
    path: &Path,
    method: &syn::ImplItemFn,
    sidecar: &crate::rsjs::StrategySidecarSummary,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    let mut unanchored = Vec::new();
    for primitive in &sidecar.dead_primitives {
        let label = primitive.label.as_deref().unwrap_or("<unlabeled>");
        let message = format!("`{label}` {} declaration is not reachable", primitive.kind);
        let help = rsjs_dead_client_primitive_help(&primitive.kind);
        let Some(anchor) = &primitive.source_anchor else {
            unanchored.push(format!("{} `{label}`", primitive.kind));
            continue;
        };
        if !dead_primitive_anchor_is_in_method(anchor, method) {
            continue;
        }
        if diagnostics.iter().any(|diag| {
            diag.code == "rsjs/dead-client-primitive"
                && diag.line == anchor.start_line
                && diag.column == anchor.start_column
                && diag.message == message
        }) {
            continue;
        }
        push_source_diag_with_severity(
            path,
            diagnostics,
            suppressions,
            anchor.start_line,
            anchor.start_column,
            Severity::Info,
            "rsjs/dead-client-primitive",
            &message,
            help,
        );
    }

    if unanchored.is_empty() {
        return;
    }
    let message = format!(
        "client primitive declaration(s) were not reachable: {}",
        unanchored.join(", ")
    );
    push_rsjs_strategy_cache_diag(
        path,
        method,
        suppressions,
        diagnostics,
        Severity::Info,
        "rsjs/dead-client-primitive",
        &message,
        "move required server work to ordinary prelude code, or connect the primitive to a reachable binding, handler, effect, query, or mutation call",
    );
}

