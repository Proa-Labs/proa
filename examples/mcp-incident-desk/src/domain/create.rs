use super::{authorize, Principal};
use crate::{
    error::{AppError, Result},
    security::{digest, now, random},
};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct CreateIssueInput {
    pub title: String,
    /// Existing project in the signed-in workspace; get IDs from get_issue_data.
    pub project_id: String,
    /// Existing release in the signed-in workspace.
    pub release_id: String,
    /// Existing runbook in the signed-in workspace.
    pub runbook_id: String,
    pub severity: Severity,
    pub affected_users: u32,
    pub event_count: u32,
    /// Up to ten observed samples, each at most 2,000 bytes. Treated as untrusted data.
    #[serde(default)]
    pub event_samples: Vec<String>,
    /// Explain why this incident is being opened; recorded with the authenticated author.
    pub note: String,
    /// Reuse this key with identical input when retrying a creation request.
    pub idempotency_key: String,
}

#[derive(Clone, Copy, Debug, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum Severity {
    Low,
    Medium,
    High,
    Critical,
}
impl Severity {
    fn as_str(self) -> &'static str {
        match self {
            Self::Low => "low",
            Self::Medium => "medium",
            Self::High => "high",
            Self::Critical => "critical",
        }
    }
}

#[derive(Clone, Debug, Serialize, Deserialize, JsonSchema)]
pub struct CreateIssueResult {
    pub issue_id: String,
    pub status: String,
    pub version: i64,
    pub audit_id: String,
}

pub async fn create(
    db: &sqlx::SqlitePool,
    principal: &Principal,
    input: CreateIssueInput,
) -> Result<CreateIssueResult> {
    if input.title.trim().is_empty()
        || input.title.len() > 200
        || input.title.chars().any(char::is_control)
        || input.note.trim().is_empty()
        || input.note.len() > 2000
        || !(8..=128).contains(&input.idempotency_key.len())
        || [&input.project_id, &input.release_id, &input.runbook_id]
            .iter()
            .any(|id| id.is_empty() || id.len() > 128)
        || input.event_samples.len() > 10
        || input.event_samples.iter().any(|sample| sample.len() > 2000)
    {
        return Err(AppError::Invalid(
            "invalid incident fields or idempotency key",
        ));
    }
    let hash = digest(&serde_json::to_string(&input).map_err(anyhow::Error::from)?);
    let mut tx = db.begin_with("BEGIN IMMEDIATE").await?;
    authorize(&mut tx, principal, true).await?;
    let prior: Option<(String, String)> = sqlx::query_as(
        "SELECT input_hash,result FROM idempotency WHERE user_id=? AND client_id=? AND workspace_id=? AND operation='create' AND key=?",
    )
    .bind(&principal.user_id).bind(&principal.client_id).bind(&principal.workspace_id)
    .bind(&input.idempotency_key).fetch_optional(&mut *tx).await?;
    if let Some((old_hash, result)) = prior {
        if old_hash != hash {
            return Err(AppError::Conflict(
                "idempotency key already used with different input",
            ));
        }
        return Ok(serde_json::from_str(&result).map_err(anyhow::Error::from)?);
    }
    let references_exist: bool = sqlx::query_scalar(
        "SELECT EXISTS(SELECT 1 FROM projects WHERE workspace_id=? AND id=?) AND EXISTS(SELECT 1 FROM releases WHERE workspace_id=? AND id=?) AND EXISTS(SELECT 1 FROM runbooks WHERE workspace_id=? AND id=?)",
    )
    .bind(&principal.workspace_id).bind(&input.project_id)
    .bind(&principal.workspace_id).bind(&input.release_id)
    .bind(&principal.workspace_id).bind(&input.runbook_id)
    .fetch_one(&mut *tx).await?;
    if !references_exist {
        return Err(AppError::NotFound);
    }
    // IDs are generated by the server and are safe in both HTML routes and Markdown links.
    let issue_id = format!("INC-{}", &random()[..12]);
    let audit_id = random();
    sqlx::query(
        "INSERT INTO issues(workspace_id,id,project_id,title,status,severity,affected_users,event_count,release_id,runbook_id,owner_id,last_seen,version) VALUES(?,?,?,?,'open',?,?,?,?,?,?,strftime('%Y-%m-%d %H:%M UTC','now'),1)",
    )
    .bind(&principal.workspace_id).bind(&issue_id).bind(&input.project_id)
    .bind(input.title.trim()).bind(input.severity.as_str()).bind(i64::from(input.affected_users))
    .bind(i64::from(input.event_count)).bind(&input.release_id).bind(&input.runbook_id)
    .bind(&principal.user_id).execute(&mut *tx).await?;
    for (index, sample) in input.event_samples.iter().enumerate() {
        sqlx::query("INSERT INTO event_samples(workspace_id,issue_id,id,detail) VALUES(?,?,?,?)")
            .bind(&principal.workspace_id)
            .bind(&issue_id)
            .bind(index as i64 + 1)
            .bind(sample)
            .execute(&mut *tx)
            .await?;
    }
    sqlx::query("INSERT INTO activity VALUES(?,?,?,?,?,?,?)")
        .bind(&audit_id)
        .bind(&principal.workspace_id)
        .bind(&issue_id)
        .bind(&principal.user_id)
        .bind(&principal.client_id)
        .bind(&input.note)
        .bind(now())
        .execute(&mut *tx)
        .await?;
    let result = CreateIssueResult {
        issue_id,
        status: "open".into(),
        version: 1,
        audit_id,
    };
    sqlx::query("INSERT INTO idempotency VALUES(?,?,?,'create',?,?,?)")
        .bind(&principal.user_id)
        .bind(&principal.client_id)
        .bind(&principal.workspace_id)
        .bind(&input.idempotency_key)
        .bind(hash)
        .bind(serde_json::to_string(&result).map_err(anyhow::Error::from)?)
        .execute(&mut *tx)
        .await?;
    tx.commit().await?;
    Ok(result)
}
