fn check_sync_child_in_async_template(
    path: &Path,
    block: &Block,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    struct Visitor<'a> {
        path: &'a Path,
        suppressions: &'a SuppressionComments,
        diagnostics: &'a mut Vec<Diagnostic>,
    }

    impl<'ast> Visit<'ast> for Visitor<'_> {
        fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
            if macro_path_ends(node, "html") {
                let Ok(root) = syn::parse2::<HtmlRoot>(node.mac.tokens.clone()) else {
                    visit::visit_expr_macro(self, node);
                    return;
                };
                for child in &root.nodes {
                    self.check_template_node(child);
                }
            }
            visit::visit_expr_macro(self, node);
        }
    }

    impl Visitor<'_> {
        fn check_template_node(&mut self, node: &Node) {
            match node {
                Node::Element(el) => {
                    for attr in &el.attrs {
                        if let Attribute::Dynamic { value, .. } = attr {
                            self.check_template_expr(value);
                        }
                    }
                    for child in &el.children {
                        self.check_template_node(child);
                    }
                }
                Node::Fragment(children) => {
                    for child in children {
                        self.check_template_node(child);
                    }
                }
                Node::Block(expr) => self.check_template_expr(expr),
                Node::Text(_) | Node::Doctype(_) => {}
            }
        }

        fn check_template_expr(&mut self, expr: &Expr) {
            if expr_is_async_render_wrapper(expr) {
                return;
            }
            if expr_constructs_uppercase_component(expr) {
                push_expr_diag_with_severity(
                    self.path,
                    SpanOrigin::File,
                    self.diagnostics,
                    self.suppressions,
                    expr.span(),
                    Severity::Info,
                    "render/sync-child-in-async",
                    "component-like child is embedded directly in async html! output",
                    "wrap sync children with proa_core::to_async(...) when composing inside async html!",
                );
            }
        }
    }

    let mut visitor = Visitor {
        path,
        suppressions,
        diagnostics,
    };
    visitor.visit_block(block);
}

struct HelperIndex<'a> {
    functions: HashMap<String, HelperFunction<'a>>,
}

struct HelperFunction<'a> {
    block: &'a Block,
    output: &'a syn::ReturnType,
}

impl<'a> HelperIndex<'a> {
    fn new(items: &'a [Item]) -> Self {
        let mut functions = HashMap::new();
        for item in items {
            if let Item::Fn(item_fn) = item {
                functions.insert(
                    item_fn.sig.ident.to_string(),
                    HelperFunction {
                        block: item_fn.block.as_ref(),
                        output: &item_fn.sig.output,
                    },
                );
            }
        }
        Self { functions }
    }

    fn get(&self, name: &str) -> Option<&HelperFunction<'a>> {
        self.functions.get(name)
    }
}

impl HelperFunction<'_> {
    fn returns_owned_string(&self) -> bool {
        return_type_is_owned_string(self.output)
    }
}

fn return_type_is_owned_string(output: &syn::ReturnType) -> bool {
    matches!(output, syn::ReturnType::Type(_, ty) if type_path_last_ident(ty).as_deref() == Some("String"))
}

