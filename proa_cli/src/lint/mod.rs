fn check_unused_rsjs_named_client_locals(
    path: &Path,
    block: &Block,
    suppressions: &SuppressionComments,
    diagnostics: &mut Vec<Diagnostic>,
) {
    let mut collector = RsjsNamedClientLocalCollector::default();
    collector.visit_block(block);
    if collector.locals.is_empty() {
        return;
    }

    let local_names: HashSet<String> = collector.locals.keys().cloned().collect();
    let mut usage = RsjsNamedClientLocalUsageCollector {
        local_names: &local_names,
        roots: HashSet::new(),
        edges: HashMap::new(),
        derived_edges: HashMap::new(),
        context: RsjsNamedClientLocalUseContext::ServerPrelude,
    };
    usage.visit_block(block);

    let mut reachable = HashSet::new();
    let mut stack: Vec<String> = usage.roots.into_iter().collect();
    while let Some(name) = stack.pop() {
        if !reachable.insert(name.clone()) {
            continue;
        }
        if let Some(edges) = usage.edges.get(&name) {
            stack.extend(edges.iter().cloned());
        }
    }

    let mut locals: Vec<_> = collector.locals.values().collect();
    locals.sort_by_key(|local| {
        let start = local.span.start();
        (start.line, start.column, local.name.as_str())
    });
    for local in locals {
        if reachable.contains(&local.name) {
            continue;
        }
        push_expr_diag_with_severity(
            path,
            SpanOrigin::File,
            diagnostics,
            suppressions,
            local.span,
            Severity::Info,
            "rsjs/dead-client-primitive",
            &format!(
                "`{}` {} declaration is not reachable",
                local.name, local.kind
            ),
            local.help(),
        );
    }
}

