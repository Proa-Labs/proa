use proa_codegen::{CodegenConfig, ComponentDef, ReactVersion, TsGenerator};
use std::env;
use std::error::Error;
use std::fs;
use std::io::{self, Read};
use std::path::{Path, PathBuf};

const USAGE: &str = "\
Generate React components from a Proa component-metadata manifest.

Usage:
  proa-codegen --input <manifest.json|-> [--output <directory>] [--react <18|19>]
               [--no-data-slot]

Options:
  --input <path|->       JSON array of component definitions; - reads stdin
  --output <directory>   Output directory (default: generated)
  --react <18|19>        React output style (default: 18)
  --no-data-slot         Do not emit data-slot attributes
  -h, --help             Show this help
";

struct Args {
    input: String,
    output: PathBuf,
    config: CodegenConfig,
}

fn parse_args() -> Result<Option<Args>, String> {
    let mut input = None;
    let mut output = PathBuf::from("generated");
    let mut react_version = ReactVersion::React18;
    let mut add_data_slot = true;
    let mut args = env::args().skip(1);

    while let Some(arg) = args.next() {
        match arg.as_str() {
            "-h" | "--help" => return Ok(None),
            "--input" => {
                input = Some(
                    args.next()
                        .ok_or_else(|| "--input requires a path or -".to_string())?,
                );
            }
            "--output" => {
                output = PathBuf::from(
                    args.next()
                        .ok_or_else(|| "--output requires a directory".to_string())?,
                );
            }
            "--react" => {
                react_version = match args.next().as_deref() {
                    Some("18") => ReactVersion::React18,
                    Some("19") => ReactVersion::React19,
                    Some(value) => {
                        return Err(format!(
                            "unsupported React version {value:?}; expected 18 or 19"
                        ));
                    }
                    None => return Err("--react requires 18 or 19".to_string()),
                };
            }
            "--no-data-slot" => add_data_slot = false,
            other => return Err(format!("unknown argument {other:?}")),
        }
    }

    let input = input.ok_or_else(|| "--input is required".to_string())?;
    let mut config = match react_version {
        ReactVersion::React18 => CodegenConfig::react_18(),
        ReactVersion::React19 => CodegenConfig::react_19(),
    };
    config.add_data_slot = add_data_slot;
    Ok(Some(Args {
        input,
        output,
        config,
    }))
}

fn read_manifest(input: &str) -> Result<Vec<ComponentDef>, Box<dyn Error>> {
    let source = if input == "-" {
        let mut source = String::new();
        io::stdin().read_to_string(&mut source)?;
        source
    } else {
        fs::read_to_string(input)?
    };
    Ok(serde_json::from_str(&source)?)
}

fn component_directory_name(name: &str) -> Result<String, Box<dyn Error>> {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return Err("component names cannot be empty".into());
    };
    if !(first.is_ascii_alphabetic() || first == '_')
        || !chars.all(|ch| ch.is_ascii_alphanumeric() || ch == '_')
    {
        return Err(format!("component name {name:?} is not a Rust-style identifier").into());
    }
    Ok(name.to_ascii_lowercase())
}

fn write_generated_files(
    output_dir: &Path,
    components: &[ComponentDef],
    config: &CodegenConfig,
) -> Result<(), Box<dyn Error>> {
    let components_dir = output_dir.join("components");
    let lib_dir = output_dir.join("lib");
    fs::create_dir_all(&components_dir)?;
    fs::create_dir_all(&lib_dir)?;

    fs::write(lib_dir.join("utils.ts"), TsGenerator::generate_cn_util())?;
    fs::write(
        output_dir.join("metadata.json"),
        serde_json::to_string_pretty(components)?,
    )?;
    fs::write(
        output_dir.join("manifest.ts"),
        "// Generated by proa-codegen - DO NOT EDIT\n\
         import manifestJson from './metadata.json';\n\n\
         export type ComponentManifest = typeof manifestJson;\n\
         export type ComponentName = ComponentManifest[number]['name'];\n\
         export const componentManifest = manifestJson;\n",
    )?;

    let mut component_index = String::from("// Generated by proa-codegen - DO NOT EDIT\n\n");
    for component in components {
        let directory_name = component_directory_name(&component.name)?;
        let component_dir = components_dir.join(&directory_name);
        fs::create_dir_all(&component_dir)?;
        fs::write(
            component_dir.join("recipe.ts"),
            TsGenerator::generate_recipe_file(component),
        )?;
        fs::write(
            component_dir.join(format!("{}.tsx", component.name)),
            TsGenerator::generate_component_file(component, config),
        )?;
        fs::write(
            component_dir.join("index.ts"),
            TsGenerator::generate_index_file(component),
        )?;
        component_index.push_str(&format!("export * from './{directory_name}';\n"));
    }
    fs::write(components_dir.join("index.ts"), component_index)?;
    fs::write(
        output_dir.join("index.ts"),
        "// Generated by proa-codegen - DO NOT EDIT\n\
         export * from './components';\n\
         export * from './manifest';\n",
    )?;
    Ok(())
}

fn main() -> Result<(), Box<dyn Error>> {
    let args = match parse_args() {
        Ok(Some(args)) => args,
        Ok(None) => {
            print!("{USAGE}");
            return Ok(());
        }
        Err(error) => {
            eprintln!("error: {error}\n\n{USAGE}");
            std::process::exit(2);
        }
    };

    let components = read_manifest(&args.input)?;
    write_generated_files(&args.output, &components, &args.config)?;
    println!(
        "generated {} component(s) in {} for React {}",
        components.len(),
        args.output.display(),
        match args.config.react_version {
            ReactVersion::React18 => "18",
            ReactVersion::React19 => "19",
        }
    );
    Ok(())
}
